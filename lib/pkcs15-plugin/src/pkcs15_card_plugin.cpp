// A5 (4.0 hardening): generic PKCS#15 matches via SELECT-DF probe in
// canHandleConnection, never via ATR. kAtrs (from manifest.json) is
// intentionally empty.

/// @brief Per-session key — mirrors the emrtd-plugin shape.
/// (reader, monotonic generation) is stable for a CardSession's
/// lifetime and definitively distinct from any successor session.
struct SessionKey
{
    std::string readerName;
    std::uint64_t generation{0};

    auto operator<=>(const SessionKey&) const = default;
};

SessionKey makeSessionKey(LibreSCRS::SmartCard::CardSession& session)
{
    return SessionKey{session.readerName(), LibreSCRS::SmartCard::detail::sessionGeneration(session)};
}

/// @brief Per-session plugin state.
///
/// Holds the CAN (only for PACE-protected cards) and a marker for
/// whether a successful PACE handshake has installed an SM filter on
/// the underlying PCSCConnection. The plugin can therefore re-install
/// PACE on its own when the SM filter has been torn down between
/// operations — the failure mode is a torn-down SM channel between
/// otherwise-independent plugin calls on the same card.
struct SessionContext
{
    LibreSCRS::Secure::String cachedCan;
    /// @brief Active SM channel installed by this plugin's most recent
    ///        PACE handshake. @c nullptr means: PACE not yet run, or
    ///        a sibling actor (emrtd-plugin, PKCS#11 module) ran PACE
    ///        and owns the SM filter. The plugin only attempts to
    ///        re-install PACE when @c cachedCan is non-empty.
    ///
    /// @note `shared_ptr` so the SM filter lambda captures a ref-counted
    /// handle. The SM stays alive as long as either this context OR the
    /// installed filter holds it; this prevents a dangling-pointer SEGV
    /// when the context is torn down (e.g., clearCredentials, ctx.sm.reset
    /// during PACE rotation) while a stale filter is still active on the
    /// PCSCConnection.
    std::shared_ptr<emrtd::crypto::SecureMessaging> sm;
};

/// @brief Result of an applet-reachability probe.
enum class ProbeResult {
    Ok,         ///< AID SELECT (or EF.DIR fallback) succeeded.
    NeedsPace,  ///< Card returned 6982 — PACE must be run first.
    Unreachable ///< Other failure; treat as not-PKCS#15.
};

/// @brief Quick reachability probe used to decide whether PACE is
///        required. Mirrors the logic in Pkcs15Card::bind without
///        committing to a full readProfile.
ProbeResult probeApplet(LibreSCRS::SmartCard::Internal::PCSCConnection& conn)
{
    std::vector<std::uint8_t> aid(pkcs15::kPkcs15Aid.begin(), pkcs15::kPkcs15Aid.end());
    auto aidResp = conn.transmit(LibreSCRS::SmartCard::Internal::selectByAID(aid, 0x0C));
    if (aidResp.isSuccess())
        return ProbeResult::Ok;
    if (aidResp.sw1 == 0x69 && aidResp.sw2 == 0x82)
        return ProbeResult::NeedsPace;
    return ProbeResult::Unreachable;
}

/// @brief Read EF.CardAccess from MF without authentication. Returns
///        empty on failure.
std::vector<std::uint8_t> readCardAccess(LibreSCRS::SmartCard::Internal::PCSCConnection& conn)
{
    auto r1 = conn.transmit(LibreSCRS::SmartCard::Internal::selectByFileId(0x3F, 0x00, 0x0C));
    if (!r1.isSuccess())
        r1 = conn.transmit(LibreSCRS::SmartCard::Internal::selectByFileId(0x3F, 0x00));
    if (!r1.isSuccess())
        return {};

    auto r2 = conn.transmit(LibreSCRS::SmartCard::Internal::selectByFileId(0x01, 0x1C, 0x0C));
    if (!r2.isSuccess())
        r2 = conn.transmit(LibreSCRS::SmartCard::Internal::selectByFileId(0x01, 0x1C));
    if (r2.sw1 != 0x90 && r2.sw1 != 0x62)
        return {};

    auto r3 = conn.transmit(LibreSCRS::SmartCard::Internal::APDUCommand{0x00, 0xB0, 0x00, 0x00, {}, 0, true});
    return r3.data;
}

/// @brief Install @p sm as a transmit filter on @p conn so subsequent
///        plain APDUs ride the established secure channel.
///
/// The lambda captures @p sm by shared_ptr value, so the SecureMessaging
/// stays alive as long as the filter exists on @p conn. When a new filter
/// replaces this one (or the filter is cleared), the captured shared_ptr
/// drops its ref count and the SM is destroyed iff no other refs remain.
/// This prevents a use-after-free SEGV when the SessionContext that
/// originally owned the SM is torn down (clearCredentials, ctx.sm rotation)
/// while a stale filter is still active on the connection.
void installSmFilter(LibreSCRS::SmartCard::Internal::PCSCConnection& conn,
                     std::shared_ptr<emrtd::crypto::SecureMessaging> sm)
{
    auto* connPtr = &conn;
    conn.setTransmitFilter([sm = std::move(sm), connPtr](const LibreSCRS::SmartCard::Internal::APDUCommand& cmd)
                               -> LibreSCRS::SmartCard::Internal::APDUResponse {
        auto cmdBytes = cmd.toBytes();
        auto protectedApdu = sm->protect(cmdBytes);
        if (protectedApdu.size() < 5)
            return {{}, 0x69, 0x82};

        auto resp = connPtr->transmitRaw(protectedApdu.data(), static_cast<DWORD>(protectedApdu.size()));

        while (resp.sw1 == 0x61) {
            std::uint8_t getResponseApdu[] = {0x00, 0xC0, 0x00, 0x00, resp.sw2};
            auto grResp = connPtr->transmitRaw(getResponseApdu, sizeof(getResponseApdu));
            resp.data.insert(resp.data.end(), grResp.data.begin(), grResp.data.end());
            resp.sw1 = grResp.sw1;
            resp.sw2 = grResp.sw2;
        }

        std::vector<std::uint8_t> respBytes = resp.data;
        respBytes.push_back(resp.sw1);
        respBytes.push_back(resp.sw2);

        auto result = sm->unprotectWithSW(respBytes);
        if (!result)
            return {{}, 0x69, 0x82};

        return {std::move(result->data), result->sw1, result->sw2};
    });
}

class PKCS15CardPlugin final : public LibreSCRS::Plugin::CardPlugin
{
public:
    PKCS15CardPlugin()
    {
        setIdentity(std::string{LibreSCRS::Plugin::generated::pkcs15::kPluginId},
                    std::string{LibreSCRS::Plugin::generated::pkcs15::kDisplayName},
                    /*priority=*/900);
    }

    LibreSCRS::Plugin::CardCapabilities capabilities() const override
    {
        return LibreSCRS::Plugin::generated::pkcs15::kCapabilities;
    }

    std::span<const LibreSCRS::Plugin::Atr> supportedAtrs() const noexcept override
    {
        return LibreSCRS::Plugin::generated::pkcs15::kAtrs;
    }

    bool canHandleConnection(std::span<const std::uint8_t> /*atr*/,
                             LibreSCRS::SmartCard::CardSession& session) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(session);
        try {
            pkcs15::PKCS15Card card(conn);
            if (card.probe()) {
                LibreSCRS::Internal::probeTrace("PROBE-PKCS15-CANHANDLE result=true");
                return true;
            }
            // Probe failed — if the card is PACE-gated (returns 6982 on
            // AID SELECT), still claim the slot so LC's credential
            // chooser drives setCredentials("can",...) which then runs
            // PACE inline below.
            const bool needsPace = probeApplet(conn) == ProbeResult::NeedsPace;
            LibreSCRS::Internal::probeTrace(std::string{"PROBE-PKCS15-CANHANDLE result="} +
                                            (needsPace ? "needsPace" : "false"));
            return needsPace;
        } catch (...) {
            LibreSCRS::Internal::probeTrace("PROBE-PKCS15-CANHANDLE result=false threw=true");
            return false;
        }
    }

    void setCredentials(LibreSCRS::SmartCard::CardSession& session, std::string_view key,
                        const LibreSCRS::Secure::String& value) override
    {
        if (key != "can")
            return;
        const auto mapKey = makeSessionKey(session);
        std::lock_guard lock(stateMutex);
        auto& ctx = sessions[mapKey];
        // Copy into a fresh Secure::String — Secure::String::view() exposes
        // the underlying bytes; we keep our own cleansing-on-destruction
        // copy so the caller's buffer can be released independently.
        ctx.cachedCan = LibreSCRS::Secure::String{value.view()};
        // CAN was just supplied; drop our SM ref so the next entry point
        // re-installs PACE with the (possibly updated) CAN. The filter
        // on conn captures sm by shared_ptr, so the old SM stays alive
        // until the filter is replaced by the next installSmFilter call.
        // We do NOT clearTransmitFilter here: a sibling plugin
        // (emrtd-plugin) may own the active filter for display, and
        // clearing it would break their channel mid-session.
        ctx.sm.reset();
    }

    void clearCredentials(LibreSCRS::SmartCard::CardSession& session) noexcept override
    {
        try {
            const auto mapKey = makeSessionKey(session);
            // Erase our SessionContext (drops our sm shared_ptr ref).
            // The filter lambda on conn keeps a shared_ptr ref to SM,
            // so SM stays alive for any in-flight or subsequent APDUs.
            // We do NOT clearTransmitFilter here: once SM is established
            // it must be preserved for ALL subsequent traffic until
            // something explicitly establishes a fresh PACE channel
            // (which REPLACES the filter atomically via setTransmitFilter).
            // Breaking SM mid-session would leave the card-side SM
            // context dangling and force a recovery path on the next op.
            std::lock_guard lock(stateMutex);
            sessions.erase(mapKey);
        } catch (...) {
            // clearCredentials is noexcept; swallow allocator faults.
        }
    }

    LibreSCRS::Plugin::ReadResult doReadCard(LibreSCRS::SmartCard::CardSession& session,
                                             GroupCallback onGroup) const override
    {
        using LibreSCRS::Plugin::ReadResult;
        try {
            auto& conn = LibreSCRS::SmartCard::detail::unwrap(session);
            if (auto rc = ensurePaceIfNeeded(session, conn); !rc)
                return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                      "pkcs15 readCard: PACE handshake failed");
            pkcs15::PKCS15Card card(conn);
            LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=doReadCard");
            auto profile = card.readProfile();

            LibreSCRS::Plugin::CardData data;
            data.cardType = "pkcs15";

            auto emitGroup = [&](LibreSCRS::Plugin::CardFieldGroup&& group) {
                if (onGroup)
                    onGroup(data.cardType, group);
                data.groups.push_back(std::move(group));
            };

            {
                LibreSCRS::Plugin::CardFieldGroup group;
                group.groupKey = "token";
                group.groupLabel = "Token Info";
                group.addText("label", "Label", profile.tokenInfo.label);
                group.addText("serial_number", "Serial Number", profile.tokenInfo.serialNumber);
                group.addText("manufacturer", "Manufacturer", profile.tokenInfo.manufacturer);
                emitGroup(std::move(group));
            }

            if (!profile.certificates.empty()) {
                LibreSCRS::Plugin::CardFieldGroup group;
                group.groupKey = "certificates";
                group.groupLabel = "Certificates";
                for (const auto& cert : profile.certificates) {
                    group.addText("cert_" + cert.label, cert.label, cert.label);
                }
                emitGroup(std::move(group));
            }

            if (!profile.pins.empty()) {
                LibreSCRS::Plugin::CardFieldGroup group;
                group.groupKey = "pins";
                group.groupLabel = "PINs";
                for (const auto& pin : profile.pins) {
                    int tries = card.getPINTriesLeft(pin);
                    std::string triesStr = (tries >= 0) ? std::to_string(tries) : "unknown";
                    group.addText("pin_" + pin.label, pin.label, "tries left: " + triesStr);
                }
                emitGroup(std::move(group));
            }

            return ReadResult::ok(std::move(data));
        } catch (const std::exception& ex) {
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{"pkcs15 readCard failed: "} + ex.what());
        } catch (...) {
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{"pkcs15 readCard failed (unknown error)"});
        }
    }

    LibreSCRS::Plugin::CardFieldGroup readTokenInfo(LibreSCRS::SmartCard::CardSession& session) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(session);
        ensurePaceIfNeeded(session, conn); // best-effort
        pkcs15::PKCS15Card card(conn);
        auto info = card.readTokenInfo();

        LibreSCRS::Plugin::CardFieldGroup group;
        group.groupKey = "token";
        group.groupLabel = "Token Info";
        group.addText("label", "Label", info.label);
        group.addText("serial_number", "Serial Number", info.serialNumber);
        group.addText("manufacturer", "Manufacturer", info.manufacturer);
        return group;
    }

    std::vector<LibreSCRS::Plugin::CertificateData>
    readCertificates(LibreSCRS::SmartCard::CardSession& session) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(session);
        ensurePaceIfNeeded(session, conn);
        pkcs15::PKCS15Card card(conn);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=readCertificates");
        auto profile = card.readProfile();

        std::vector<LibreSCRS::Plugin::CertificateData> result;
        for (const auto& cert : profile.certificates) {
            auto der = card.readCertificate(cert);
            if (der.empty())
                continue;

            LibreSCRS::Plugin::CertificateData cd;
            cd.label = cert.label;
            cd.derBytes = std::move(der);

            for (const auto& key : profile.privateKeys) {
                if (key.id == cert.id) {
                    if (key.path.size() >= 2) {
                        cd.keyFID = static_cast<std::uint16_t>((key.path[key.path.size() - 2] << 8) |
                                                               key.path[key.path.size() - 1]);
                    } else if (key.keyReference != 0) {
                        cd.keyFID = static_cast<std::uint16_t>(key.keyReference);
                    } else {
                        cd.keyFID = std::uint16_t{1};
                    }
                    if (key.keySizeBits != 0)
                        cd.keySizeBits = key.keySizeBits;
                    break;
                }
            }

            result.push_back(std::move(cd));
        }

        return result;
    }

    std::vector<LibreSCRS::Plugin::PinStatusEntry> getPINList(LibreSCRS::SmartCard::CardSession& session) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(session);
        ensurePaceIfNeeded(session, conn);
        pkcs15::PKCS15Card card(conn);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=getPINList");
        auto profile = card.readProfile();

        std::vector<LibreSCRS::Plugin::PinStatusEntry> result;
        for (const auto& pin : profile.pins) {
            LibreSCRS::Plugin::PinStatusEntry entry;
            entry.label = pin.label;
            entry.reference = pin.pinReference;
            entry.initialized = pin.initialized;

            if (pin.initialized) {
                try {
                    int tries = card.getPINTriesLeft(pin);
                    if (tries >= 0)
                        entry.retriesLeft = tries;
                    entry.blocked = (tries == 0);
                } catch (...) {
                    // leave entry.retriesLeft as std::nullopt
                }
            }

            if (pin.minLength > 0)
                entry.minLength = static_cast<std::size_t>(pin.minLength);
            if (pin.maxLength > 0)
                entry.maxLength = static_cast<std::size_t>(pin.maxLength);
            entry.canChange = !pin.unblockingPin && pin.label.find("PUK") == std::string::npos;
            result.push_back(std::move(entry));
        }
        return result;
    }

    LibreSCRS::Plugin::PINResult changePIN(LibreSCRS::SmartCard::CardSession& session, std::string_view pinLabel,
                                           const LibreSCRS::Secure::String& oldPin,
                                           const LibreSCRS::Secure::String& newPin) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(session);
        ensurePaceIfNeeded(session, conn);
        pkcs15::PKCS15Card card(conn);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=changePIN");
        auto profile = card.readProfile();

        const pkcs15::PinInfo* pinInfo = findPinByLabel(profile, pinLabel);
        if (!pinInfo)
            pinInfo = findUserPin(profile);
        if (!pinInfo) {
            LibreSCRS::Plugin::PINResult r;
            r.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return r;
        }

        auto r = card.changePIN(*pinInfo, oldPin.view(), newPin.view());
        LibreSCRS::Plugin::PINResult result;
        if (r.retriesLeft >= 0)
            result.retriesLeft = r.retriesLeft;
        result.blocked = r.blocked;
        if (r.success)
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::Ok;
        else if (result.blocked)
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::Blocked;
        else if (result.retriesLeft.has_value())
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::InvalidPin;
        else
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
        return result;
    }

    std::optional<int> getPINTriesLeft(LibreSCRS::SmartCard::CardSession& session) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(session);
        ensurePaceIfNeeded(session, conn);
        pkcs15::PKCS15Card card(conn);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=getPINTriesLeft");
        auto profile = card.readProfile();
        auto* pin = findUserPin(profile);
        if (!pin)
            return std::nullopt;

        int tries = card.getPINTriesLeft(*pin);
        if (tries < 0)
            return std::nullopt;
        return tries;
    }

    LibreSCRS::Plugin::PINResult verifyPIN(LibreSCRS::SmartCard::CardSession& session,
                                           const LibreSCRS::Secure::String& pin) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(session);
        ensurePaceIfNeeded(session, conn);
        pkcs15::PKCS15Card card(conn);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=verifyPIN");
        auto profile = card.readProfile();
        auto* pinInfo = findUserPin(profile);
        if (!pinInfo)
            return {};

        auto r = card.verifyPIN(*pinInfo, pin.view());
        LibreSCRS::Plugin::PINResult out;
        if (r.retriesLeft >= 0)
            out.retriesLeft = r.retriesLeft;
        out.blocked = r.blocked;
        if (r.success)
            out.outcome = LibreSCRS::Plugin::PINResultOutcome::Ok;
        else if (out.blocked)
            out.outcome = LibreSCRS::Plugin::PINResultOutcome::Blocked;
        else if (out.retriesLeft.has_value())
            out.outcome = LibreSCRS::Plugin::PINResultOutcome::InvalidPin;
        else
            out.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
        return out;
    }

private:
    /// @brief Lazily install PACE on @p conn when this card is PACE-gated
    ///        and the active session has a cached CAN but no live SM
    ///        filter. Returns true if the card is reachable (either
    ///        directly or after PACE), false otherwise.
    ///
    /// The single contract: after a true return, @p conn either
    /// (a) accepts plain AID SELECT, or (b) carries an SM filter that
    /// transparently wraps subsequent APDUs. Callers can then construct
    /// a fresh @c pkcs15::PKCS15Card and proceed as if PACE were never
    /// a concern.
    bool ensurePaceIfNeeded(LibreSCRS::SmartCard::CardSession& session,
                            LibreSCRS::SmartCard::Internal::PCSCConnection& conn) const
    {
        // Cheap probe: if AID SELECT works (or EF.DIR fallback would),
        // PACE is not required for this card.
        const auto state = probeApplet(conn);
        if (state == ProbeResult::Ok)
            return true;
        if (state == ProbeResult::Unreachable) {
            // Probe says "not 6982" but also "not 9000" — likely a card
            // that needs EF.DIR fallback. Defer to the helper's own
            // probe inside the caller; report success here so the
            // caller's PKCS15Card::probe() / selectApplet() take over.
            return true;
        }

        // state == NeedsPace. We need a CAN.
        const auto mapKey = makeSessionKey(session);
        SessionContext* ctx = nullptr;
        std::unique_lock lock(stateMutex);
        auto it = sessions.find(mapKey);
        if (it == sessions.end() || it->second.cachedCan.view().empty()) {
            // No CAN; nothing we can do here. Either a sibling actor
            // (emrtd-plugin) has already installed PACE on this conn —
            // in which case the SM filter is live and AID SELECT would
            // have succeeded above — or the credentials hand-off hasn't
            // happened yet and the caller will see a 6982 downstream.
            return false;
        }
        ctx = &it->second;

        // If we have an SM channel already and AID SELECT still returned
        // 6982, the channel was torn down by the card (reset / timeout).
        // Drop our SM ref; the fresh installSmFilter below will REPLACE
        // the existing filter atomically (old lambda destroyed → old SM
        // shared_ptr ref dropped → old SM destroyed when refs hit 0).
        // We do NOT clearTransmitFilter before the new install: any
        // intervening APDU through the stale filter is harmless (worst
        // case the card returns 6987 / 6982 which the caller handles)
        // and breaking the filter mid-flight would force a recovery
        // path on any sibling/concurrent operation.
        if (ctx->sm)
            ctx->sm.reset();

        auto cardAccess = readCardAccess(conn);
        if (cardAccess.empty())
            return false;

        auto entries = emrtd::crypto::parseCardAccessWithParams(cardAccess);
        if (entries.empty())
            return false;

        auto canView = ctx->cachedCan.view();
        std::optional<emrtd::crypto::SessionKeys> sessionKeys;
        std::string winningOid;
        for (const auto& [oid, paramId] : entries) {
            emrtd::crypto::PACEParams params;
            params.oid = oid;
            params.passwordType = emrtd::crypto::PACEPasswordType::CAN;
            params.password = std::vector<std::uint8_t>(canView.begin(), canView.end());
            params.paramId = paramId;
            sessionKeys = emrtd::crypto::performPACE(conn, params);
            if (!params.password.empty())
                OPENSSL_cleanse(params.password.data(), params.password.size());
            if (sessionKeys) {
                winningOid = oid;
                break;
            }
        }
        if (!sessionKeys)
            return false;

        auto smAlgo = emrtd::crypto::paceOIDToSMAlgorithm(winningOid);
        ctx->sm = std::make_shared<emrtd::crypto::SecureMessaging>(*sessionKeys, smAlgo);
        installSmFilter(conn, ctx->sm);
        return true;
    }

    static const pkcs15::PinInfo* findUserPin(const pkcs15::PKCS15Profile& profile)
    {
        for (const auto& pin : profile.pins) {
            if (pin.local && pin.initialized)
                return &pin;
        }
        for (const auto& pin : profile.pins) {
            if (pin.initialized)
                return &pin;
        }
        return nullptr;
    }

    static const pkcs15::PinInfo* findPinByLabel(const pkcs15::PKCS15Profile& profile, std::string_view pinLabel)
    {
        if (pinLabel.empty())
            return nullptr;

        for (const auto& pin : profile.pins) {
            if (pin.label == pinLabel)
                return &pin;
        }

        constexpr std::string_view prefix = "pin_";
        if (pinLabel.starts_with(prefix)) {
            std::string_view suffix = pinLabel.substr(prefix.size());
            for (const auto& pin : profile.pins) {
                if (pin.label == suffix)
                    return &pin;
            }
            try {
                std::string suffixStr{suffix};
                size_t consumed = 0;
                int ref = std::stoi(suffixStr, &consumed);
                if (consumed == suffixStr.size() && ref >= 0 && ref <= 0xFF) {
                    for (const auto& pin : profile.pins) {
                        if (pin.pinReference == static_cast<uint8_t>(ref))
                            return &pin;
                    }
                }
            } catch (const std::exception&) {
                // fall through
            }
        }

        return nullptr;
    }

    mutable std::mutex stateMutex;
    mutable std::map<SessionKey, SessionContext> sessions;
};

