/// @brief Plugin-side memory of whether this card session is PACE-gated.
///
/// PACE / SM ownership lives on @ref LibreSCRS::SmartCard::CardSession;
/// the plugin only needs to know *which* activation flavour to request
/// for a given operation (plain vs. PACE-CAN). The CAN itself is held by
/// CardSession via @ref CardSession::setPaceSecret. This struct is
/// intentionally tiny.
struct SessionContext
{
    /// @brief @c true after a successful "PACE required" probe (canHandle
    ///        returned needsPace) or after @ref setCredentials("can", ...)
    ///        has been called. When false the plugin uses
    ///        @ref activateChannelFor (PlainChannel) instead of
    ///        @ref activateChannelWithSm.
    bool requiresPace{false};

    /// @brief The signing PIN, deposited per-session by the caller via
    ///        @ref setCredentials("pin", ...) immediately before a sign.
    ///
    /// Held here (not on @ref CardSession, which only owns PACE secrets) as a
    /// transient, session-scoped @ref LibreSCRS::Secure::String: it is consumed
    /// by @ref doSign (hash-on-card RSA-SHA256, where the lower
    /// @c PKCS15Card::sign owns the atomic verify+sign and therefore needs the
    /// PIN) and wiped when the session entry is erased by
    /// @ref clearCredentials. The map is keyed by session, so no cross-reader
    /// bleed. @since 4.3
    LibreSCRS::Secure::String pin;
};

LibreSCRS::SmartCard::AppletAid pkcs15AppletAid()
{
    return LibreSCRS::SmartCard::AppletAid::fromBytes(
        std::span<const std::uint8_t>{pkcs15::kPkcs15Aid.data(), pkcs15::kPkcs15Aid.size()});
}

/// @brief Result of a cheap reachability probe against the AID, used to
///        decide whether PACE is required.
enum class ProbeResult {
    Ok,         ///< Plain SELECT succeeded — no SM needed for this card.
    NeedsPace,  ///< Card returned 6982 — PACE must be run first.
    Unreachable ///< Other failure; treat as not-PKCS#15.
};

ProbeResult probeApplet(LibreSCRS::SmartCard::Internal::PCSCConnection& conn)
{
    std::vector<std::uint8_t> aid(pkcs15::kPkcs15Aid.begin(), pkcs15::kPkcs15Aid.end());
    auto aidResp = conn.transmit(LibreSCRS::SmartCard::Internal::selectByAID(aid, 0x0C));
    if (aidResp.isSuccess())
        return ProbeResult::Ok;
    if (aidResp.sw1 == 0x69 && aidResp.sw2 == 0x82)
        return ProbeResult::NeedsPace;
    return ProbeResult::Unreachable;
}

/// @brief Acquire an @ref ActiveChannelHolder appropriate for this session.
///
/// PACE-gated cards take the SM activation path
/// (@ref CardSession::activateChannelWithSm with @c PaceRequest{Can});
/// non-PACE cards take the plain path. The CAN — if needed — must have
/// been deposited in CardSession's cache via @ref setCredentials before
/// this call; CardSession's preflight short-circuits with
/// @c CredentialsRequired if neither a cached CAN nor a provider is
/// available. A PaceChannel installed earlier by emrtd-plugin (when the
/// user came through the display flow first) is reused via wrapped
/// SELECT on the existing SM tunnel — no rePACE.
std::expected<LibreSCRS::SmartCard::ActiveChannelHolder, LibreSCRS::SecureChannel::ChannelActivationError>
acquireChannel(LibreSCRS::SmartCard::CardSession& session, bool requiresPace)
{
    auto aid = pkcs15AppletAid();
    if (requiresPace) {
        return session.activateChannelWithSm(
            aid, LibreSCRS::SmartCard::PaceRequest{LibreSCRS::Auth::PaceSecretKind::Can}, LibreSCRS::CancelToken{});
    }
    return session.activateChannelFor(aid, LibreSCRS::CancelToken{});
}

/// Suite label markers come exclusively from hardware-captured EF.TokenInfo
/// labels — never invented or inferred: a marker enters this table only
/// after being read off a physical card through this very plugin's
/// SM/PACE path. Unmatched cards stay FamilyId::Unknown (conservative
/// derivation only).
LibreSCRS::Plugin::Internal::FamilyId resolveFamilyId(const pkcs15::PKCS15Profile& profile)
{
    struct LabelMarker
    {
        std::string_view marker;
        LibreSCRS::Plugin::Internal::FamilyId family;
    };
    // "SSCDv1 PACE MD": EF.TokenInfo label captured 2026-07-20 from certain
    // IAS-ECC hash-on-card SSCDs over the contact interface (production
    // readProfile path).
    static constexpr std::array<LabelMarker, 1> kMarkers{
        {{"SSCDv1 PACE MD", LibreSCRS::Plugin::Internal::FamilyId::AppletSuiteGen1}}};
    for (const auto& m : kMarkers)
        if (profile.tokenInfo.label.find(m.marker) != std::string_view::npos)
            return m.family;
    return LibreSCRS::Plugin::Internal::FamilyId::Unknown;
}

/// @brief True when @p path points into @p family's signature (QSCD) DF —
///        prefix comparison against the family's signature-DF path.
bool inFamilySignatureDf(LibreSCRS::Plugin::Internal::FamilyId family, const std::vector<std::uint8_t>& path)
{
    if (family == LibreSCRS::Plugin::Internal::FamilyId::AppletSuiteGen1) {
        static constexpr std::array<std::uint8_t, 4> kAppletSuiteGen1SignatureDf{0x3F, 0x00, 0x0D, 0xF5};
        return path.size() >= kAppletSuiteGen1SignatureDf.size() &&
               std::equal(kAppletSuiteGen1SignatureDf.begin(), kAppletSuiteGen1SignatureDf.end(), path.begin());
    }
    return false;
}

/// @brief Builds the AODF-evidence fields @c unblockPIN, @c
///        activateTransportPin and @c activateSigningKey all fill
///        IDENTICALLY for one already-resolved credential (Task 12 review
///        Minor: this ~11-line block was verbatim-duplicated between
///        @c unblockPIN and @c activateTransportPin; extracted here so a
///        third override doesn't copy it a third time).
///
/// Deliberately does NOT set @ref
/// LibreSCRS::Plugin::Internal::PinEvidence::authIdChainTarget (only @c
/// unblockPIN's PUK chain-resolution needs it — set by that call site
/// after calling this) nor @c blocked (only @c getPINList's counter-probe
/// pass populates that; a mutation call never probes counters, so the
/// conservative @c false default stands).
///
/// @param pinInfo   The already-resolved credential (by label or, for
///                  @c activateSigningKey, by scanning for the
///                  holder-activatable record).
/// @param family    Resolved family, for the signature-DF marker.
/// @param quirks    The family's quirk row; @c nullptr is tolerated
///                  (mirrors @c getPINList's own inline construction)
///                  though every current call site has already null-checked it.
/// @param paceGated Session-level PACE requirement (@c requiresPaceFor).
LibreSCRS::Plugin::Internal::PinEvidence buildPinEvidence(const pkcs15::PinInfo& pinInfo,
                                                          LibreSCRS::Plugin::Internal::FamilyId family,
                                                          const LibreSCRS::Plugin::Internal::FamilyQuirks* quirks,
                                                          bool paceGated)
{
    using LibreSCRS::Plugin::Internal::PinEvidence;
    PinEvidence e;
    e.label = pinInfo.label;
    e.reference = pinInfo.pinReference;
    e.ownId = pinInfo.id;
    e.localScope = pinInfo.local;
    e.inQscdDf = inFamilySignatureDf(family, pinInfo.path);
    e.soPinFlag = pinInfo.soPin;
    e.unblockingPinFlag = pinInfo.unblockingPin;
    e.unblockDisabledFlag = pinInfo.unblockDisabled;
    e.changeDisabledFlag = pinInfo.changeDisabled;
    e.initialized = pinInfo.initialized;
    e.paceEvidence = (paceGated || (quirks && quirks->usesPace)) && pinInfo.changeDisabled && pinInfo.unblockDisabled;
    return e;
}

class PKCS15CardPlugin final : public LibreSCRS::Plugin::CardPlugin
{
public:
    PKCS15CardPlugin()
    {
        setIdentity(std::string{LibreSCRS::Plugin::generated::pkcs15::kPluginId},
                    std::string{LibreSCRS::Plugin::generated::pkcs15::kDisplayName},
                    /*priority=*/900);
    }

    LibreSCRS::Plugin::CardCapabilities capabilities() const override
    {
        return LibreSCRS::Plugin::generated::pkcs15::kCapabilities;
    }

    // NAM / IAS-ECC and other PACE-gated PKCS#15 cards require the CAN (PACE)
    // before any read; plain PKCS#15 cards do not. The base derives this from a
    // STATIC activation profile (plain -> None), but this plugin decides PACE at
    // RUNTIME via the probe (see canHandle / requiresPaceFor), so the static
    // derivation under-reports as None. Report it correctly here: PaceCan when
    // the card needs PACE (which is also the signal that selects on-card SHA-256
    // signing — IAS-ECC SSCDs hash the message on-card), else None.
    LibreSCRS::Auth::PreReadAuthMethod preReadAuth(LibreSCRS::SmartCard::CardSession& session) const override
    {
        return requiresPaceFor(session) ? LibreSCRS::Auth::PreReadAuthMethod::PaceCan
                                        : LibreSCRS::Auth::PreReadAuthMethod::None;
    }

    std::span<const LibreSCRS::Plugin::Atr> supportedAtrs() const noexcept override
    {
        return LibreSCRS::Plugin::generated::pkcs15::kAtrs;
    }

    bool canHandleConnection(std::span<const std::uint8_t> /*atr*/,
                             LibreSCRS::SmartCard::CardSession& session) const override
    {
        const auto mapKey = makeSessionKey(session);
        try {
            // A live SM channel on the session means PACE/BAC has already
            // been established (e.g. user came through the emrtd-plugin
            // display flow first). PACE SM is session-scoped per BSI
            // TR-03110 §3 — a plain SELECT-AID over the raw connection
            // would reset the card-side SM context, breaking the next
            // wrapped APDU. Probe the PKCS#15 applet through the SM-aware
            // CardSession::transmitInternal funnel instead: wrapped
            // SELECT-AID stays inside the SM tunnel and the response SW
            // distinguishes "applet present" (0x9000 — Serbian eID and
            // similar hybrid cards, accept the candidate and route
            // subsequent acquireChannel() through the SM activation fast
            // path) from "applet absent" (e.g. 0x6A82 — foreign passport
            // that exposes only the eMRTD LDS and no PKCS#15 layer;
            // decline so the host does not attach an empty Token section
            // to a card it cannot actually read certificates from).
            if (session.hasLiveSecureChannel()) {
                std::vector<std::uint8_t> probeAid(::pkcs15::kPkcs15Aid.begin(), ::pkcs15::kPkcs15Aid.end());
                auto probeResp =
                    session.transmitInternal(LibreSCRS::SmartCard::Internal::selectByAID(probeAid, /*p2=*/0x0C));
                if (probeResp.isSuccess()) {
                    std::lock_guard lock(stateMutex);
                    sessions[mapKey].requiresPace = true;
                    LibreSCRS::Internal::probeTrace("PROBE-PKCS15-CANHANDLE result=needsPace via=liveSm-wrapped-probe");
                    return true;
                }
                char swBuf[12];
                std::snprintf(swBuf, sizeof(swBuf), "0x%04X", probeResp.statusWord());
                LibreSCRS::Internal::probeTrace(std::string{"PROBE-PKCS15-CANHANDLE result=false "
                                                            "via=liveSm-wrapped-probe SW="} +
                                                swBuf);
                return false;
            }
            auto& conn = LibreSCRS::SmartCard::detail::unwrap(session);
            // Cheap, no-SM probe to decide between PlainChannel (contact
            // PKCS#15 families) and PaceChannel (PACE-gated contactless
            // families) for subsequent operations. The actual applet
            // selection happens later through
            // CardSession::activateChannel{For,WithSm}.
            const auto state = probeApplet(conn);
            if (state == ProbeResult::Ok) {
                std::lock_guard lock(stateMutex);
                sessions[mapKey].requiresPace = false;
                LibreSCRS::Internal::probeTrace("PROBE-PKCS15-CANHANDLE result=true");
                return true;
            }
            if (state == ProbeResult::NeedsPace) {
                std::lock_guard lock(stateMutex);
                sessions[mapKey].requiresPace = true;
                LibreSCRS::Internal::probeTrace("PROBE-PKCS15-CANHANDLE result=needsPace");
                return true;
            }
            // Unreachable: try the full PKCS15Card probe path which includes
            // EF.DIR fallback (some cards expose PKCS#15 only through the
            // EF.DIR application registry, not via direct AID SELECT).
            LibreSCRS::SecureChannel::PlainChannel probeChannel(conn, LibreSCRS::SmartCard::AppletAid{});
            pkcs15::PKCS15Card card(probeChannel);
            if (card.probe()) {
                std::lock_guard lock(stateMutex);
                sessions[mapKey].requiresPace = false;
                LibreSCRS::Internal::probeTrace("PROBE-PKCS15-CANHANDLE result=true");
                return true;
            }
            LibreSCRS::Internal::probeTrace("PROBE-PKCS15-CANHANDLE result=false");
            return false;
        } catch (...) {
            LibreSCRS::Internal::probeTrace("PROBE-PKCS15-CANHANDLE result=false threw=true");
            return false;
        }
    }

    void setCredentials(LibreSCRS::SmartCard::CardSession& session, std::string_view key,
                        const LibreSCRS::Secure::String& value) override
    {
        if (key == "can") {
            // CardSession owns the CAN cache; this plugin simply forwards the
            // secret. Successful PACE activation through CardSession reuses
            // the same cache slot whether the secret was deposited by
            // emrtd-plugin (display flow) or by us (direct sign).
            session.setPaceSecret(LibreSCRS::Auth::PaceSecretKind::Can, LibreSCRS::Secure::String{value.view()});
            std::lock_guard lock(stateMutex);
            sessions[makeSessionKey(session)].requiresPace = true;
            return;
        }
        if (key == "pin") {
            // The signing PIN: held per-session for the immediately following
            // hash-on-card sign (see @ref doSign), where the lower
            // PKCS15Card::sign owns the atomic verify+MSE+PSO and therefore
            // needs the PIN. Wiped by clearCredentials. CardSession only owns
            // PACE secrets, so the eSign PIN lives here (session-keyed map ->
            // no cross-reader bleed), NOT in the PACE cache.
            std::lock_guard lock(stateMutex);
            sessions[makeSessionKey(session)].pin = LibreSCRS::Secure::String{value.view()};
            return;
        }
    }

    void clearCredentials(LibreSCRS::SmartCard::CardSession& session) noexcept override
    {
        try {
            std::lock_guard lock(stateMutex);
            sessions.erase(makeSessionKey(session));
        } catch (...) {
            // clearCredentials is noexcept; swallow allocator faults.
        }
    }

    LibreSCRS::Plugin::ReadResult doReadCard(LibreSCRS::SmartCard::CardSession& session,
                                             GroupCallback onGroup) const override
    {
        using LibreSCRS::Plugin::ReadResult;
        try {
            auto holderResult = acquireChannel(session, requiresPaceFor(session));
            if (!holderResult)
                return mapActivationError(holderResult.error(), "pkcs15 doReadCard");
            auto holder = std::move(*holderResult);
            auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
            if (channel == nullptr)
                return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                      "pkcs15 doReadCard: channel not active after activation");

            pkcs15::PKCS15Card card(*channel);
            LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=doReadCard");
            auto profile = card.readProfile();

            LibreSCRS::Plugin::CardData data;
            data.cardType = "pkcs15";

            auto emitGroup = [&](LibreSCRS::Plugin::CardFieldGroup&& group) {
                if (onGroup)
                    onGroup(data.cardType, group);
                data.groups.push_back(std::move(group));
            };

            {
                LibreSCRS::Plugin::CardFieldGroup group;
                group.groupKey = "token";
                group.groupLabel = "Token Info";
                group.addText("label", "Label", profile.tokenInfo.label);
                group.addText("serial_number", "Serial Number", profile.tokenInfo.serialNumber);
                group.addText("manufacturer", "Manufacturer", profile.tokenInfo.manufacturer);
                emitGroup(std::move(group));
            }

            if (!profile.certificates.empty()) {
                LibreSCRS::Plugin::CardFieldGroup group;
                group.groupKey = "certificates";
                group.groupLabel = "Certificates";
                for (const auto& cert : profile.certificates) {
                    group.addText("cert_" + cert.label, cert.label, cert.label);
                }
                emitGroup(std::move(group));
            }

            // PIN state is surfaced via the typed getPINList() override
            // (PinStatusEntry vector), not via the readCard() data groups.

            return ReadResult::ok(std::move(data));
        } catch (const std::exception& ex) {
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{"pkcs15 readCard failed: "} + ex.what());
        } catch (...) {
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{"pkcs15 readCard failed (unknown error)"});
        }
    }

    LibreSCRS::Plugin::CardFieldGroup readTokenInfo(LibreSCRS::SmartCard::CardSession& session) const override
    {
        // Best-effort token-info read. Every failure mode below degrades to
        // a partial or empty group rather than escaping an exception:
        //   - channel activation failure → empty group, no fields
        //   - card.readTokenInfo() throw (select / SM teardown / parse) →
        //     empty group, no fields
        //   - per-field addText failure → the offending field is skipped,
        //     siblings are preserved
        //
        // The presentation layer relies on the group's key/label being set
        // up-front so it can render its placeholder header from an empty
        // group; the fields vector is permitted to be empty when nothing
        // could be read.
        LibreSCRS::Plugin::CardFieldGroup group;
        group.groupKey = "token";
        group.groupLabel = "Token Info";

        // Diagnostics route through std::clog with the
        // "[librescrs.pkcs15.plugin]" category prefix to keep this TU (and
        // therefore the dlopen'd plugin .so) Qt-free. LM plugins are loaded
        // by LibreCelik (Qt6), LibreKDE (Qt6+KF6), LibreMac BridgeNative
        // (Swift), and p11-kit consumers (Kleopatra, Firefox, gpgsm,
        // Thunderbird) — pulling Qt into the plugin would break the Qt-free
        // hosts. Pattern mirrors MonitorService.cpp's flood-warning emission.
        std::optional<LibreSCRS::SmartCard::ActiveChannelHolder> holderOpt;
        try {
            auto holderResult = acquireChannel(session, requiresPaceFor(session));
            if (!holderResult) {
                std::clog << "[librescrs.pkcs15.plugin] readTokenInfo: acquireChannel failed with code "
                          << static_cast<int>(holderResult.error()) << "\n";
                return group;
            }
            holderOpt.emplace(std::move(*holderResult));
        } catch (const std::exception& ex) {
            std::clog << "[librescrs.pkcs15.plugin] readTokenInfo: acquireChannel threw: " << ex.what() << "\n";
            return group;
        } catch (...) {
            std::clog << "[librescrs.pkcs15.plugin] readTokenInfo: acquireChannel threw (non-std exception)\n";
            return group;
        }

        auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(*holderOpt);
        if (channel == nullptr) {
            std::clog << "[librescrs.pkcs15.plugin] readTokenInfo: channel not active after activation\n";
            return group;
        }

        pkcs15::TokenInfo info;
        try {
            pkcs15::PKCS15Card card(*channel);
            info = card.readTokenInfo();
        } catch (const std::exception& ex) {
            std::clog << "[librescrs.pkcs15.plugin] readTokenInfo: card.readTokenInfo threw: " << ex.what() << "\n";
            return group;
        } catch (...) {
            std::clog << "[librescrs.pkcs15.plugin] readTokenInfo: card.readTokenInfo threw (non-std exception)\n";
            return group;
        }

        // Per-field guard: skip empty values up-front (CardFieldGroup::addText
        // throws std::logic_error on `(empty value, empty fields)` by design,
        // so unconditional calls would cascade a single missing field into a
        // fully empty group). The try/catch around addText is the defensive
        // tail: even if the upstream contract relaxes, the plugin still
        // returns whatever sibling fields succeeded.
        auto safeAddText = [&](std::string_view key, std::string_view label, std::string_view value) {
            if (value.empty())
                return;
            try {
                group.addText(key, label, value);
            } catch (const std::exception& ex) {
                std::clog << "[librescrs.pkcs15.plugin] readTokenInfo: addText(" << key << ") threw: " << ex.what()
                          << "\n";
            } catch (...) {
                std::clog << "[librescrs.pkcs15.plugin] readTokenInfo: addText threw (non-std exception)\n";
            }
        };

        safeAddText("label", "Label", info.label);
        safeAddText("serial_number", "Serial Number", info.serialNumber);
        safeAddText("manufacturer", "Manufacturer", info.manufacturer);
        return group;
    }

    std::vector<LibreSCRS::Plugin::CertificateData>
    readCertificates(LibreSCRS::SmartCard::CardSession& session) const override
    {
        std::vector<LibreSCRS::Plugin::CertificateData> result;
        auto holderResult = acquireChannel(session, requiresPaceFor(session));
        if (!holderResult)
            return result;
        auto holder = std::move(*holderResult);
        auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
        if (channel == nullptr)
            return result;

        pkcs15::PKCS15Card card(*channel);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=readCertificates");
        auto profile = card.readProfile();

        for (const auto& cert : profile.certificates) {
            auto der = card.readCertificate(cert);
            if (der.empty())
                continue;

            LibreSCRS::Plugin::CertificateData cd;
            cd.label = cert.label;
            cd.derBytes = std::move(der);
            // The PKCS#15 object id IS the PKCS#11 CKA_ID the bridge exposes
            // (see pkcs15_pkcs11_slot.cpp) — surface it so the in-process sign
            // path can select THIS exact key by CKA_ID rather than the
            // non-unique label.
            cd.ckaId = cert.id;

            for (const auto& key : profile.privateKeys) {
                if (key.id == cert.id) {
                    if (key.path.size() >= 2) {
                        cd.keyFID = static_cast<std::uint16_t>((key.path[key.path.size() - 2] << 8) |
                                                               key.path[key.path.size() - 1]);
                    } else if (key.keyReference != 0) {
                        cd.keyFID = static_cast<std::uint16_t>(key.keyReference);
                    } else {
                        cd.keyFID = std::uint16_t{1};
                    }
                    if (key.keySizeBits != 0)
                        cd.keySizeBits = key.keySizeBits;
                    break;
                }
            }

            result.push_back(std::move(cd));
        }

        return result;
    }

    std::vector<LibreSCRS::Plugin::PinStatusEntry> getPINList(LibreSCRS::SmartCard::CardSession& session) const override
    {
        std::vector<LibreSCRS::Plugin::PinStatusEntry> result;
        const bool paceGated = requiresPaceFor(session);
        auto holderResult = acquireChannel(session, paceGated);
        if (!holderResult)
            return result;
        auto holder = std::move(*holderResult);
        auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
        if (channel == nullptr)
            return result;

        pkcs15::PKCS15Card card(*channel);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=getPINList");
        auto profile = card.readProfile();

        using LibreSCRS::Plugin::Internal::PinEvidence;
        const auto family = resolveFamilyId(profile);
        const auto* quirks = LibreSCRS::Plugin::Internal::findFamilyQuirks(family);

        // Evidence pass: one entry per AODF object, plus the counter probe —
        // GATED on the family's verified probe safety. The probe reads the
        // full DOCP (CV family: retries/uses/unblocks; non-DOCP cards: all
        // absent), falling back to the empty-VERIFY status form for
        // retriesLeft when DOCP yields none — the no-regression guard so a
        // probeSafe family that is not a DOCP card never loses retriesLeft.
        // Both forms are non-consuming on probeSafe families; without a
        // quirk row neither ever reaches the wire and counters stay absent
        // (getPINList must not consume retry/usage budget).
        std::vector<PinEvidence> evidence;
        std::vector<LibreSCRS::Plugin::CredentialCounters> countersById;
        evidence.reserve(profile.pins.size());
        countersById.reserve(profile.pins.size());
        for (const auto& pin : profile.pins) {
            PinEvidence e;
            // An empty AODF label must never be advertised verbatim: the
            // changePIN selector contract reserves the EMPTY selector for
            // the legacy default-PIN fallback, so "" would alias this
            // record onto a DIFFERENT credential. The documented
            // "pin_<reference>" form is the non-aliasing substitute —
            // findPinByLabel accepts it verbatim and addresses the record
            // by its reference.
            e.label = pin.label.empty() ? "pin_" + std::to_string(static_cast<unsigned>(pin.pinReference)) : pin.label;
            e.reference = pin.pinReference;
            e.ownId = pin.id;
            e.localScope = pin.local;
            e.inQscdDf = inFamilySignatureDf(family, pin.path);
            e.soPinFlag = pin.soPin;
            e.unblockingPinFlag = pin.unblockingPin;
            e.unblockDisabledFlag = pin.unblockDisabled;
            e.changeDisabledFlag = pin.changeDisabled;
            e.initialized = pin.initialized;
            // CAN evidence needs card-level PACE nature AND the AODF's CAN
            // shape — change-disabled + unblock-disabled (a value printed on
            // the card can be neither changed nor unblocked). "Card-level" =
            // the session used PACE (paceGated, e.g. contactless) OR this
            // family's cards use PACE (usesPace) — the latter recognises the
            // CAN on the contact interface too, where no PACE handshake
            // occurs. The shape gate keeps a fixed service PIN on a non-PACE
            // card from ever being promoted to a CAN.
            e.paceEvidence = (paceGated || (quirks && quirks->usesPace)) && pin.changeDisabled && pin.unblockDisabled;

            LibreSCRS::Plugin::CredentialCounters cardCounters;
            if (pin.initialized && quirks && quirks->probeSafe) {
                try {
                    cardCounters = card.readCounters(pin); // DOCP (CV: full; non-DOCP: empty)
                    if (!cardCounters.retriesLeft.has_value()) {
                        const int tries = card.getPINTriesLeft(pin); // VERIFY fallback
                        if (tries >= 0)
                            cardCounters.retriesLeft = tries;
                    }
                } catch (...) {
                    // leave absent — graceful
                }
            }
            e.blocked = cardCounters.retriesLeft.has_value() && *cardCounters.retriesLeft == 0;
            countersById.push_back(cardCounters); // parallel to `evidence`
            evidence.push_back(std::move(e));
        }

        // Chain resolution (the caller-side contract of the derivation
        // engine): a PIN whose protecting authId resolves to ANOTHER auth
        // object records that object's FULL id bytes (matched against the
        // target's ownId during derivation) and marks the resolved object
        // as the unblocking authority.
        for (std::size_t i = 0; i < profile.pins.size(); ++i) {
            const auto& protecting = profile.pins[i].authId;
            if (protecting.empty())
                continue;
            for (std::size_t j = 0; j < profile.pins.size(); ++j) {
                if (j == i || profile.pins[j].id != protecting)
                    continue;
                evidence[i].authIdChainTarget = protecting;
                evidence[j].unblockingPinFlag = true;
                break;
            }
        }

        // Derivation pass — runs after the evidence set is COMPLETE so the
        // cross-object rules (PUK presentability) see every entry.
        for (std::size_t i = 0; i < evidence.size(); ++i) {
            auto entry = LibreSCRS::Plugin::Internal::derivePinStatus(evidence[i], evidence, quirks);
            const auto& cc = countersById[i];
            if (cc.retriesLeft.has_value())
                entry.retriesLeft = cc.retriesLeft;
            if (cc.retriesMax.has_value())
                entry.retriesMax = cc.retriesMax; // card-first; else derivation's quirk value stands
            if (cc.usesLeft.has_value())
                entry.usesLeft = cc.usesLeft;
            if (cc.usesMax.has_value())
                entry.usesMax = cc.usesMax;
            if (cc.unblocksLeft.has_value())
                entry.unblocksLeft = cc.unblocksLeft;
            const auto& pin = profile.pins[i];
            if (pin.minLength > 0)
                entry.minLength = static_cast<std::size_t>(pin.minLength);
            if (pin.maxLength > 0)
                entry.maxLength = static_cast<std::size_t>(pin.maxLength);
            result.push_back(std::move(entry));
        }
        return result;
    }

    LibreSCRS::Plugin::PINResult changePIN(LibreSCRS::SmartCard::CardSession& session, std::string_view pinLabel,
                                           const LibreSCRS::Secure::String& oldPin,
                                           const LibreSCRS::Secure::String& newPin) const override
    {
        LibreSCRS::Plugin::PINResult result;
        auto holderResult = acquireChannel(session, requiresPaceFor(session));
        if (!holderResult) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }
        auto holder = std::move(*holderResult);
        auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
        if (channel == nullptr) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }

        pkcs15::PKCS15Card card(*channel);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=changePIN");
        auto profile = card.readProfile();

        const pkcs15::PinInfo* pinInfo = findPinByLabel(profile, pinLabel);
        if (!pinInfo && !pinLabel.empty()) {
            // A non-empty selector that matches no AODF object is a
            // refusal, not a fallback: silently changing a different
            // credential on a multi-PIN card is never acceptable. Only the
            // EMPTY selector keeps the legacy default-PIN fallback below.
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }
        if (!pinInfo)
            pinInfo = findUserPin(profile);
        if (!pinInfo) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }

        auto r = card.changePIN(*pinInfo, oldPin.view(), newPin.view());
        if (r.retriesLeft >= 0)
            result.retriesLeft = r.retriesLeft;
        result.blocked = r.blocked;
        result.outcome = LibreSCRS::Plugin::classifyPinOutcome(result, r.success);
        return result;
    }

    /// @brief PUK-based unblock via ISO RESET RETRY COUNTER.
    ///
    /// Mirrors changePIN above exactly for credential resolution / channel /
    /// transaction (acquireChannel, readProfile, findPinByLabel with the
    /// same hard-fail-on-selector-miss contract) and swaps in
    /// card.resetRetryCounter (Task 9's builder) in place of
    /// card.changePIN. The unblock STYLE — and therefore the RESET RETRY
    /// COUNTER P1 and the resulting on-wire data shape — is resolved by
    /// calling the SAME derivation function getPINList uses
    /// (derivePinStatus), fed the SAME evidence shape, never a hardcoded
    /// switch.
    ///
    /// @note Only takes effect for a family whose quirk row has verified
    ///       RRC knowledge for this credential's kind (currently: none —
    ///       AppletSuiteGen1's row deliberately withholds rrcVariantKnown
    ///       until a hardware campaign confirms the byte values Task 8
    ///       seeded as ISO defaults, i.e. still [HW-VERIFY]); everything
    ///       else — including a genuinely unknown family — falls back to
    ///       the base Unsupported contract untouched.
    LibreSCRS::Plugin::PINResult unblockPIN(LibreSCRS::SmartCard::CardSession& session, std::string_view pinLabel,
                                            const LibreSCRS::Secure::String& puk,
                                            const LibreSCRS::Secure::String& newPin) const override
    {
        LibreSCRS::Plugin::PINResult result;
        auto holderResult = acquireChannel(session, requiresPaceFor(session));
        if (!holderResult) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }
        auto holder = std::move(*holderResult);
        auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
        if (channel == nullptr) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }

        pkcs15::PKCS15Card card(*channel);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=unblockPIN");
        auto profile = card.readProfile();

        const pkcs15::PinInfo* pinInfo = findPinByLabel(profile, pinLabel);
        if (!pinInfo && !pinLabel.empty()) {
            // Same hard-fail contract as changePIN: a non-empty selector
            // that matches no AODF object is a refusal, never a fallback.
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }
        if (!pinInfo)
            pinInfo = findUserPin(profile);
        if (!pinInfo) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }

        const auto family = resolveFamilyId(profile);
        const auto* quirks = LibreSCRS::Plugin::Internal::findFamilyQuirks(family);
        if (quirks == nullptr) {
            // No family knowledge at all: this plugin has no verified
            // unblock command form for this card. Same contract as the base
            // CardPlugin::unblockPIN default.
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::Unsupported;
            return result;
        }

        // Evidence for the addressed credential PLUS its resolved PUK (if
        // the AODF names one via authId) — exactly the fields getPINList's
        // evidence pass fills for these two objects, just without the
        // counter probe (this call doesn't need retriesLeft/usesLeft). The
        // PUK sub-entry below deliberately omits .blocked too (unlike
        // getPINList's evidence pass, which populates it from the card
        // counters): this is safe because the RRC attempt below is the
        // authoritative state check regardless — a truly exhausted PUK gets
        // classified via the 6983 branch, never a stale/absent pre-check
        // here.
        using LibreSCRS::Plugin::Internal::PinEvidence;
        PinEvidence target = buildPinEvidence(*pinInfo, family, quirks, requiresPaceFor(session));
        if (!pinInfo->authId.empty())
            target.authIdChainTarget = pinInfo->authId;

        std::vector<PinEvidence> allEvidence{target};
        if (!pinInfo->authId.empty()) {
            for (const auto& p : profile.pins) {
                if (p.id == pinInfo->authId) {
                    PinEvidence pukEvidence;
                    pukEvidence.ownId = p.id;
                    allEvidence.push_back(pukEvidence);
                    break;
                }
            }
        }

        const auto entry = LibreSCRS::Plugin::Internal::derivePinStatus(allEvidence.front(), allEvidence, quirks);
        if (!entry.unblockable) {
            // No verified RRC variant for this credential's kind (or its PUK
            // isn't chain-resolvable / is vetoed) — Unsupported, and
            // critically, no APDU reaches the wire: the style is genuinely
            // data-driven, never assumed.
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::Unsupported;
            return result;
        }

        // Style -> (P1, on-wire data shape) decision, extracted to a pure
        // free function (Task 11 review fix) so it is unit-testable without
        // card I/O or a production injection seam — see resolveUnblockApdu's
        // doc comment for the classifyPinOutcome-precedent rationale.
        const auto apdu =
            LibreSCRS::Plugin::Internal::resolveUnblockApdu(entry.unblockStyle, *quirks, puk.view(), newPin.view());

        auto r = card.resetRetryCounter(*pinInfo, apdu.puk, apdu.newPin, apdu.p1);
        if (r.retriesLeft >= 0)
            result.retriesLeft = r.retriesLeft; // attributed to the PUK
        result.blocked = r.blocked;
        result.outcome = LibreSCRS::Plugin::classifyPinOutcome(result, r.success);

        // secStateClear: best-effort cleanup, per quirks->secStateClear.
        // performSecStateClear returns void by design — see its comment —
        // so a cleanup failure structurally cannot flip `result.outcome`
        // away from the RRC's own classification (mutation-success is
        // authoritative: never cause the client to re-prompt and burn
        // another PUK use over a cosmetic re-select failure).
        performSecStateClear(card, *quirks);

        return result;
    }

    /// @brief Transport-born SIGN PIN activation via ISO CHANGE REFERENCE
    ///        DATA.
    ///
    /// Mirrors changePIN/unblockPIN's credential-resolution / channel /
    /// transaction shape (acquireChannel, readProfile, findPinByLabel),
    /// using the new PKCS15Card::changeReferenceData(p1) verb (this task's
    /// sibling to Task 11's resetRetryCounter) — a new verb, not a
    /// replacement for card.changePIN, which this override never calls.
    /// Unlike changePIN/unblockPIN, there is no legacy "empty selector ->
    /// default PIN" fallback here: findUserPin() requires pin.initialized,
    /// which a transport-state SIGN PIN by definition is NOT, so it could
    /// never resolve the addressed credential anyway — an empty selector
    /// is therefore ALSO a hard-fail, not merely the non-empty-miss case
    /// changePIN/unblockPIN carve out.
    ///
    /// Gating and the P1-driven data shape are resolved by calling the
    /// SAME derivation getPINList/unblockPIN use (derivePinStatus / the
    /// sibling resolveTransportChangeApdu pure function beside
    /// resolveUnblockApdu), never a hardcoded switch.
    ///
    /// @note Only takes effect for a family whose quirk row asserts
    ///       supportsTransportPin AND whose evidence resolves this
    ///       credential's kind/state to SignPin/Transport; everything
    ///       else — including a genuinely unknown family, or this SAME
    ///       family once the credential is already personalized — falls
    ///       back to the base Unsupported contract untouched, and
    ///       critically no CHANGE REFERENCE DATA APDU reaches the wire in
    ///       that case.
    LibreSCRS::Plugin::PINResult activateTransportPin(LibreSCRS::SmartCard::CardSession& session,
                                                      std::string_view pinLabel,
                                                      const LibreSCRS::Secure::String& transportValue,
                                                      const LibreSCRS::Secure::String& newPin) const override
    {
        LibreSCRS::Plugin::PINResult result;
        auto holderResult = acquireChannel(session, requiresPaceFor(session));
        if (!holderResult) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }
        auto holder = std::move(*holderResult);
        auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
        if (channel == nullptr) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }

        pkcs15::PKCS15Card card(*channel);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=activateTransportPin");
        auto profile = card.readProfile();

        const pkcs15::PinInfo* pinInfo = findPinByLabel(profile, pinLabel);
        if (!pinInfo) {
            // Hard-fail on ANY resolution miss, empty selector included —
            // see the override's doc comment above for why no default-PIN
            // fallback exists here.
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }

        const auto family = resolveFamilyId(profile);
        const auto* quirks = LibreSCRS::Plugin::Internal::findFamilyQuirks(family);
        if (quirks == nullptr) {
            // No family knowledge at all: same contract as the base
            // CardPlugin::activateTransportPin default.
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::Unsupported;
            return result;
        }

        // Evidence for the addressed credential — exactly the fields
        // getPINList's evidence pass fills for kind/state classification (no
        // counter probe: this is a mutation call, not a read).
        using LibreSCRS::Plugin::Internal::PinEvidence;
        const PinEvidence target = buildPinEvidence(*pinInfo, family, quirks, requiresPaceFor(session));

        const std::vector<PinEvidence> allEvidence{target};
        const auto entry = LibreSCRS::Plugin::Internal::derivePinStatus(target, allEvidence, quirks);
        if (!entry.activatable) {
            // Not a transport-state SIGN PIN on a transport-capable family —
            // Unsupported, and the style resolution is genuinely
            // data-driven, never assumed.
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::Unsupported;
            return result;
        }

        // Form -> (P1, on-wire data shape) decision, extracted to a pure
        // free function up front (mirrors Task 11's resolveUnblockApdu) so
        // it is unit-testable without card I/O.
        const auto apdu = LibreSCRS::Plugin::Internal::resolveTransportChangeApdu(quirks->transportChangeP1,
                                                                                  transportValue.view(), newPin.view());

        if (apdu.p1 == 0x01) {
            // Prior-auth form: VERIFY the transport value first, THEN
            // CHANGE with new-only data.
            auto vr = card.verifyPIN(*pinInfo, transportValue.view());
            if (!vr.success) {
                if (vr.retriesLeft >= 0)
                    result.retriesLeft = vr.retriesLeft; // attributed to the transport value
                result.blocked = vr.blocked;
                result.outcome = LibreSCRS::Plugin::classifyPinOutcome(result, false);
                return result;
            }
            // VERIFY established a verified security state on the card. An
            // intra-verb drop between here and the CHANGE below must not
            // leave that state leaked on the card — best-effort
            // secStateClear before reporting failure truthfully.
            try {
                auto r = card.changeReferenceData(*pinInfo, apdu.oldData, apdu.newData, apdu.p1);
                if (r.retriesLeft >= 0)
                    result.retriesLeft = r.retriesLeft;
                result.blocked = r.blocked;
                result.outcome = LibreSCRS::Plugin::classifyPinOutcome(result, r.success);
            } catch (...) {
                performSecStateClear(card, *quirks);
                result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
                return result;
            }
        } else {
            // One-shot form: a single CHANGE REFERENCE DATA call carries
            // transport||new — no separate VERIFY, so no intervening
            // verified state can leak.
            auto r = card.changeReferenceData(*pinInfo, apdu.oldData, apdu.newData, apdu.p1);
            if (r.retriesLeft >= 0)
                result.retriesLeft = r.retriesLeft;
            result.blocked = r.blocked;
            result.outcome = LibreSCRS::Plugin::classifyPinOutcome(result, r.success);
        }

        // secStateClear: best-effort cleanup, per quirks->secStateClear.
        // Mutation-success is authoritative: a later clear failure must
        // never flip an already-successful outcome (same guarantee as
        // unblockPIN).
        performSecStateClear(card, *quirks);
        return result;
    }

    /// @brief Deactivated SIGN key activation via ISO ACTIVATE.
    ///
    /// Mirrors unblockPIN/activateTransportPin's
    /// channel/transaction/quirks-lookup shape, but the base virtual
    /// (CardPlugin.h ~737) takes NO pin label: the credential to
    /// VERIFY+ACTIVATE is resolved ENTIRELY internally, by building the
    /// SAME evidence set getPINList/unblockPIN/activateTransportPin build
    /// (buildPinEvidence, reused verbatim — Part A's DRY fix) for EVERY
    /// AODF object and running it through the SAME derivePinStatus,
    /// looking for the one whose derived record is holder-activatable
    /// (@ref LibreSCRS::Plugin::PinStatusEntry::keyActivatable — "Holder
    /// can activate that key through this software", PinStatusEntry.h:131)
    /// — never a hardcoded label or PinKind.
    ///
    /// @note [Documented gap, the same shape as unblockPIN's RRC gap
    ///       above — see that override's doc comment.] Per
    ///       derivePinStatus's own comment
    ///       (pin_lifecycle_derivation.cpp ~101-108), keyActivatable (and
    ///       keyActivationPending) keep their conservative FALSE default
    ///       for EVERY family today: asserting a deactivated signing key
    ///       needs key/certificate-state evidence no plugin reads yet.
    ///       Unlike unblockPIN's rrcVariantKnown — a per-family bool a
    ///       future hardware campaign could flip — there is today no
    ///       FamilyQuirks/PinEvidence field at all whose value could make
    ///       keyActivatable true; the derivation function simply never
    ///       computes it from evidence. So this override IS genuinely
    ///       data-driven (it reuses the shared derivation engine end to
    ///       end and never special-cases a credential by label or kind),
    ///       but has NO reachable success path through the real registry
    ///       funnel — for ANY family, including AppletSuiteGen1 even
    ///       though its quirk row already carries ISO-default keyActivate
    ///       bytes (Task 8, still [HW-VERIFY], i.e. NOT hardware-confirmed)
    ///       — until a future increment teaches derivePinStatus to assert
    ///       keyActivatable from real key/certificate evidence. See the
    ///       Pkcs15KeyActivation card-verb-layer tests (mirroring the
    ///       Pkcs15ResetRetryCounter / Pkcs15ChangeReferenceDataActivation
    ///       precedent) for the coverage this gap requires instead of an
    ///       end-to-end fixture: they prove PKCS15Card::activate's own SW
    ///       mapping (9000 / 6985-idempotent / other-failure) and the
    ///       VERIFY-side classifyPinOutcome fact this override composes,
    ///       unbranched, into its Ok / KeyActivationFailed result below.
    LibreSCRS::Plugin::PINResult activateSigningKey(LibreSCRS::SmartCard::CardSession& session,
                                                    const LibreSCRS::Secure::String& signPin) const override
    {
        LibreSCRS::Plugin::PINResult result;
        const bool paceGated = requiresPaceFor(session);
        auto holderResult = acquireChannel(session, paceGated);
        if (!holderResult) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }
        auto holder = std::move(*holderResult);
        auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
        if (channel == nullptr) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }

        pkcs15::PKCS15Card card(*channel);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=activateSigningKey");
        auto profile = card.readProfile();

        const auto family = resolveFamilyId(profile);
        const auto* quirks = LibreSCRS::Plugin::Internal::findFamilyQuirks(family);
        if (quirks == nullptr) {
            // No family knowledge at all: same contract as the base
            // CardPlugin::activateSigningKey default.
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::Unsupported;
            return result;
        }

        // Evidence pass over EVERY AODF object (buildPinEvidence), plus the
        // same chain-resolution pass getPINList runs, so a future
        // derivation change that makes keyActivatable chain-dependent sees
        // a fully-formed evidence set here too — never special-cased for
        // this verb.
        using LibreSCRS::Plugin::Internal::PinEvidence;
        std::vector<PinEvidence> evidence;
        evidence.reserve(profile.pins.size());
        for (const auto& pin : profile.pins)
            evidence.push_back(buildPinEvidence(pin, family, quirks, paceGated));
        for (std::size_t i = 0; i < profile.pins.size(); ++i) {
            const auto& protecting = profile.pins[i].authId;
            if (protecting.empty())
                continue;
            for (std::size_t j = 0; j < profile.pins.size(); ++j) {
                if (j == i || profile.pins[j].id != protecting)
                    continue;
                evidence[i].authIdChainTarget = protecting;
                evidence[j].unblockingPinFlag = true;
                break;
            }
        }

        // Resolve the ONE credential whose derived record is holder-
        // activatable — never a hardcoded label/kind (see the doc comment
        // above: no family asserts this today, so this loop always falls
        // through to Unsupported in production).
        const pkcs15::PinInfo* signPinInfo = nullptr;
        for (std::size_t i = 0; i < profile.pins.size(); ++i) {
            if (LibreSCRS::Plugin::Internal::derivePinStatus(evidence[i], evidence, quirks).keyActivatable) {
                signPinInfo = &profile.pins[i];
                break;
            }
        }
        if (signPinInfo == nullptr) {
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::Unsupported;
            return result;
        }

        // Self-contained, ONE lock (PIV-PIN-ALWAYS discipline): VERIFY the
        // operational SIGN PIN, then ACTIVATE the key, against this SAME
        // `card`/channel/transaction — never CardPlugin::verifyPIN, which
        // would be a second, separate transaction.
        auto vr = card.verifyPIN(*signPinInfo, signPin.view());
        if (!vr.success) {
            if (vr.retriesLeft >= 0)
                result.retriesLeft = vr.retriesLeft; // attributed to the SIGN PIN
            result.blocked = vr.blocked;
            result.outcome = LibreSCRS::Plugin::classifyPinOutcome(result, false);
            return result;
        }

        // VERIFY established a verified security state on the card. An
        // intra-verb drop between here and ACTIVATE must not leave it
        // leaked — best-effort secStateClear before reporting failure
        // truthfully (same guard as activateTransportPin's prior-auth
        // form).
        try {
            auto ar = card.activate(*signPinInfo, quirks->keyActivate.p1, quirks->keyActivate.p2);
            // 6985 is the idempotent already-active case
            // (PKCS15Card::activate folds it into `success` — see its doc
            // comment); both that and a fresh 9000 report Ok here.
            // Anything else is KeyActivationFailed: VERIFY succeeded but
            // the key ACTIVATE step failed.
            result.outcome = ar.success ? LibreSCRS::Plugin::PINResultOutcome::Ok
                                        : LibreSCRS::Plugin::PINResultOutcome::KeyActivationFailed;
        } catch (...) {
            performSecStateClear(card, *quirks);
            result.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return result;
        }

        // secStateClear: best-effort cleanup, per quirks->secStateClear.
        // Mutation-success is authoritative: a later clear failure must
        // never flip an already-successful outcome (same guarantee as
        // unblockPIN/activateTransportPin).
        performSecStateClear(card, *quirks);
        return result;
    }

    LibreSCRS::Plugin::CredentialCounters readCounters(LibreSCRS::SmartCard::CardSession& session,
                                                       std::string_view pinLabel) const override
    {
        auto holderResult = acquireChannel(session, requiresPaceFor(session));
        if (!holderResult)
            return {};
        auto holder = std::move(*holderResult);
        auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
        if (channel == nullptr)
            return {};
        pkcs15::PKCS15Card card(*channel);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=readCounters");
        auto profile = card.readProfile();
        const pkcs15::PinInfo* pin = pinLabel.empty() ? findUserPin(profile) : findPinByLabel(profile, pinLabel);
        if (!pin)
            return {};
        // CV family: full DOCP read. Fall back to the VERIFY (63 Cx) retry
        // read whenever DOCP is unavailable (non-CV card, gated object, parse
        // miss) so retriesLeft NEVER regresses for non-DOCP cards / the
        // signing path. This is the no-regression guard.
        const auto family = resolveFamilyId(profile);
        const auto* quirks = LibreSCRS::Plugin::Internal::findFamilyQuirks(family);
        LibreSCRS::Plugin::CredentialCounters c;
        if (quirks && quirks->probeSafe)
            c = card.readCounters(*pin);
        if (!c.retriesLeft.has_value()) {
            const int tries = card.getPINTriesLeft(*pin);
            if (tries >= 0)
                c.retriesLeft = tries;
        }
        return c;
    }

    // Raw on-card RSA decrypt is not yet implemented for the generic PKCS#15
    // fallback family. Unlike the opensc plugin (which binds an
    // sc_pkcs15_card_t and delegates to sc_pkcs15_decipher), this plugin
    // operates over the LM-native pkcs15::PKCS15Card abstraction on an SM
    // channel and has no libopensc card handle. A raw-decrypt path would
    // require a dedicated MSE:Set-CT (P2=0xB8) + PSO DECIPHER APDU sequence on
    // pkcs15::PKCS15Card mirroring its sign() path — new on-card crypto rather
    // than a delegation — so it is deferred. Returning NotImplemented
    // explicitly (rather than inheriting the base default) keeps the gap
    // visible to callers and documents the reason at the override site.
    LibreSCRS::Plugin::DecipherResult doDecipher(LibreSCRS::SmartCard::CardSession& /*session*/,
                                                 std::uint16_t /*keyReference*/,
                                                 std::span<const std::uint8_t> /*ciphertext*/,
                                                 LibreSCRS::Plugin::DecipherMechanism /*mechanism*/) const override
    {
        LibreSCRS::Plugin::DecipherResult r;
        r.outcome = LibreSCRS::Plugin::DecipherResultOutcome::NotImplemented;
        return r;
    }

    // Hash-on-card RSA-SHA256 signing for the IAS-ECC / PKCS#15 family
    // (NAM: SCE 8.0-C2V0 SSCD). The caller deposits the signing
    // PIN via setCredentials("pin", ...) immediately before this call (the same
    // per-session seam used for the CAN). PKCS15Card::sign owns the atomic
    // select + verifyPIN + MSE(0x28) + PSO over the RAW message — the exact
    // EVP-verified sequence the LibreCelik / AdES path uses — so we do NOT
    // pre-verify here. Only RSA_SHA256 (raw message, card hashes) is honoured;
    // a caller-supplied DigestInfo (RSA_PKCS) is rejected by these cards, so
    // that mechanism inherits the base NotImplemented.
    LibreSCRS::Plugin::SignResult doSign(LibreSCRS::SmartCard::CardSession& session, std::uint16_t keyReference,
                                         std::span<const std::uint8_t> data,
                                         LibreSCRS::Plugin::SignMechanism mechanism) const override
    {
        LibreSCRS::Plugin::SignResult r;
        // Honour RSA_SHA256 ONLY for cards that actually hash on-card — i.e.
        // PACE-gated IAS-ECC SSCDs (NAM). For any other mechanism, OR a plain
        // PKCS#15 card (no PACE) that expects a caller-built DigestInfo, return
        // NotImplemented so the agent falls back to its verify + RSA_PKCS
        // DigestInfo path. This matters because RsaSha256Pkcs1's on-card attempt
        // set (pkcs15_card.cpp) is narrower than RsaPkcs1 and brute-forces
        // hash-on-card algos, which is wrong for a DigestInfo card; gating here
        // keeps the fallback alive for the rest of the PKCS#15 family (only the
        // NAM hash-on-card path is exercised + HW-verified today).
        if (mechanism != LibreSCRS::Plugin::SignMechanism::RSA_SHA256 || !requiresPaceFor(session)) {
            r.outcome = LibreSCRS::Plugin::SignResultOutcome::NotImplemented;
            return r;
        }
        // Pull the per-session signing PIN deposited by setCredentials("pin").
        LibreSCRS::Secure::String pin;
        {
            std::lock_guard lock(stateMutex);
            auto it = sessions.find(makeSessionKey(session));
            if (it != sessions.end())
                pin = LibreSCRS::Secure::String{it->second.pin.view()};
        }
        if (pin.view().empty()) {
            r.outcome = LibreSCRS::Plugin::SignResultOutcome::PluginError; // no PIN deposited
            return r;
        }
        try {
            auto holderResult = acquireChannel(session, requiresPaceFor(session));
            if (!holderResult) {
                r.outcome = LibreSCRS::Plugin::SignResultOutcome::PluginError;
                return r;
            }
            auto holder = std::move(*holderResult);
            auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
            if (channel == nullptr) {
                r.outcome = LibreSCRS::Plugin::SignResultOutcome::PluginError;
                return r;
            }
            pkcs15::PKCS15Card card(*channel);
            auto profile = card.readProfile();

            // Resolve the private key whose on-card file id matches keyReference
            // (the keyFID readCertificates surfaced from the PrKDF path).
            const pkcs15::PrivateKeyInfo* matched = nullptr;
            for (const auto& key : profile.privateKeys) {
                std::uint16_t fid;
                if (key.path.size() >= 2)
                    fid = static_cast<std::uint16_t>((key.path[key.path.size() - 2] << 8) |
                                                     key.path[key.path.size() - 1]);
                else if (key.keyReference != 0)
                    fid = static_cast<std::uint16_t>(key.keyReference);
                else
                    fid = std::uint16_t{1};
                if (fid == keyReference) {
                    matched = &key;
                    break;
                }
            }
            const pkcs15::PinInfo* pinInfo = findUserPin(profile);
            if (matched == nullptr || pinInfo == nullptr) {
                r.outcome = LibreSCRS::Plugin::SignResultOutcome::PluginError;
                return r;
            }

            // PKCS15Card::sign takes both a DigestInfo and the raw data; for the
            // RsaSha256Pkcs1 scheme the winning attempt on a hash-on-card SSCD
            // is {algo 0x28, rawData} (the card hashes). Pass the raw message in
            // both slots, mirroring the EVP-verified in-process path
            // (Pkcs15Slot::signData). pin.view() references `pin`, alive here.
            std::vector<std::uint8_t> dataVec(data.begin(), data.end());
            auto sig = card.sign(*matched, pin.view(), *pinInfo, dataVec, dataVec, pkcs15::SignScheme::RsaSha256Pkcs1);
            if (sig.empty()) {
                r.outcome = LibreSCRS::Plugin::SignResultOutcome::PluginError;
                return r;
            }
            r.signature = std::move(sig);
            r.outcome = LibreSCRS::Plugin::SignResultOutcome::Ok;
            return r;
        } catch (...) {
            // PKCS15Card::sign throws a generic runtime_error on wrong PIN /
            // exhausted attempts. LIMITATION (constrained by the no-ABI-bump
            // rule — SignResultOutcome has no AuthFailed variant and the throw
            // is untyped): a wrong eSign PIN folds to PluginError here, which the
            // agent maps to CardError -> CKR_DEVICE_ERROR, NOT CKR_PIN_INCORRECT.
            // Counter-safety is preserved per op: the agent does a SINGLE attempt
            // (no retry on PluginError; the DigestInfo fallback fires only on
            // NotImplemented), so the card's PIN counter is touched at most once,
            // and the HW test's g_pinFailed latch blocks further attempts. A host
            // must NOT auto-retry on CKR_DEVICE_ERROR (it is not a PIN-retry hint).
            r.outcome = LibreSCRS::Plugin::SignResultOutcome::PluginError;
            return r;
        }
    }

    LibreSCRS::Plugin::PINResult verifyPIN(LibreSCRS::SmartCard::CardSession& session,
                                           const LibreSCRS::Secure::String& pin) const override
    {
        LibreSCRS::Plugin::PINResult out;
        auto holderResult = acquireChannel(session, requiresPaceFor(session));
        if (!holderResult) {
            out.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return out;
        }
        auto holder = std::move(*holderResult);
        auto* channel = LibreSCRS::SmartCard::Internal::HolderChannelAccessor::channel(holder);
        if (channel == nullptr) {
            out.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return out;
        }

        pkcs15::PKCS15Card card(*channel);
        LibreSCRS::Internal::probeTrace("PROBE-READPROFILE call=verifyPIN");
        auto profile = card.readProfile();
        auto* pinInfo = findUserPin(profile);
        if (!pinInfo)
            return {};

        auto r = card.verifyPIN(*pinInfo, pin.view());
        if (r.retriesLeft >= 0)
            out.retriesLeft = r.retriesLeft;
        out.blocked = r.blocked;
        out.outcome = LibreSCRS::Plugin::classifyPinOutcome(out, r.success);
        return out;
    }

private:
    bool requiresPaceFor(LibreSCRS::SmartCard::CardSession& session) const
    {
        std::lock_guard lock(stateMutex);
        auto it = sessions.find(makeSessionKey(session));
        return it != sessions.end() && it->second.requiresPace;
    }

    // Clears any security state a mutating card verb (RESET RETRY COUNTER /
    // CHANGE REFERENCE DATA / ACTIVATE) established, per the family's
    // quirks->secStateClear method. Returns void BY DESIGN: this is a
    // best-effort cleanup step, never a classifier — a caller cannot flip an
    // already-computed PINResult::outcome using a value this function
    // doesn't return, which is the structural guarantee behind the
    // "mutation-success is authoritative" invariant (see unblockPIN). Only
    // logs on failure.
    static void performSecStateClear(pkcs15::PKCS15Card& card,
                                     const LibreSCRS::Plugin::Internal::FamilyQuirks& quirks) noexcept
    {
        using SecStateClear = LibreSCRS::Plugin::Internal::FamilyQuirks::SecStateClear;
        switch (quirks.secStateClear) {
        case SecStateClear::ReselectApplet:
            try {
                if (!card.selectApplet())
                    std::clog << "[librescrs.pkcs15.plugin] secStateClear: re-select failed\n";
            } catch (const std::exception& ex) {
                std::clog << "[librescrs.pkcs15.plugin] secStateClear: re-select threw: " << ex.what() << "\n";
            } catch (...) {
                std::clog << "[librescrs.pkcs15.plugin] secStateClear: re-select threw (non-std exception)\n";
            }
            break;
        }
    }

    static LibreSCRS::Plugin::ReadResult mapActivationError(LibreSCRS::SecureChannel::ChannelActivationError err,
                                                            const char* what)
    {
        using LibreSCRS::Plugin::ReadResult;
        using Err = LibreSCRS::SecureChannel::ChannelActivationError;
        std::string suffix;
        switch (err) {
        case Err::Cancelled:
        case Err::UserCancelled:
            suffix = "user cancelled";
            return ReadResult::authenticationFailed(LibreSCRS::Auth::ErrorKeys::authFailed(),
                                                    std::string{what} + ": " + suffix);
        case Err::PaceWrongSecret:
            suffix = "wrong CAN";
            return ReadResult::authenticationFailed(LibreSCRS::Auth::ErrorKeys::authFailed(),
                                                    std::string{what} + ": " + suffix);
        case Err::CredentialsRequired:
            suffix = "CAN required";
            return ReadResult::authenticationFailed(LibreSCRS::Auth::ErrorKeys::authFailed(),
                                                    std::string{what} + ": " + suffix);
        case Err::CardRemoved:
            suffix = "card removed";
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{what} + ": " + suffix);
        case Err::SelectAppletFailed:
            suffix = "failed to select PKCS#15 applet";
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{what} + ": " + suffix);
        case Err::PaceUnsupported:
            suffix = "card does not support PACE";
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{what} + ": " + suffix);
        default:
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{what} + ": activation failed");
        }
    }

    static const pkcs15::PinInfo* findUserPin(const pkcs15::PKCS15Profile& profile)
    {
        using LibreSCRS::Pkcs15::Internal::isUserPin;
        for (const auto& pin : profile.pins) {
            if (isUserPin(pin) && pin.local && pin.initialized)
                return &pin;
        }
        for (const auto& pin : profile.pins) {
            if (isUserPin(pin) && pin.initialized)
                return &pin;
        }
        return nullptr;
    }

    static const pkcs15::PinInfo* findPinByLabel(const pkcs15::PKCS15Profile& profile, std::string_view pinLabel)
    {
        if (pinLabel.empty())
            return nullptr;

        for (const auto& pin : profile.pins) {
            if (pin.label == pinLabel)
                return &pin;
        }

        constexpr std::string_view prefix = "pin_";
        if (pinLabel.starts_with(prefix)) {
            std::string_view suffix = pinLabel.substr(prefix.size());
            // Reference form FIRST: pin_<decimal> is the selector getPINList
            // synthesizes for empty-label records, so it must resolve by
            // reference before any legacy suffix-label interpretation — a
            // record whose AODF label is literally "4" must not intercept
            // the advertised selector of the empty-label record with
            // reference 4.
            try {
                std::string suffixStr{suffix};
                size_t consumed = 0;
                int ref = std::stoi(suffixStr, &consumed);
                if (consumed == suffixStr.size() && ref >= 0 && ref <= 0xFF) {
                    for (const auto& pin : profile.pins) {
                        if (pin.pinReference == static_cast<uint8_t>(ref))
                            return &pin;
                    }
                }
            } catch (const std::exception&) {
                // not a numeric suffix — fall through to the label form
            }
            // Legacy suffix-label form: "pin_<label>" addressing a record by
            // its (non-empty) AODF label. Reached for non-numeric suffixes
            // and for numeric suffixes matching no reference.
            for (const auto& pin : profile.pins) {
                if (pin.label == suffix)
                    return &pin;
            }
        }

        return nullptr;
    }

    mutable std::mutex stateMutex;
    mutable std::map<SessionKey, SessionContext> sessions;
};

