void OpenSCSession::resetCardState() noexcept
{
    // Partial teardown. Order matters: PKCS#15 binding holds references into
    // the underlying sc_card, so unbind before disconnect. The disconnect
    // goes through the bridge reader ops (no-op at the wire) — zero PC/SC
    // calls. ctx and bridge SURVIVE: the next operation re-activates and
    // re-binds over the same context; sc_establish_context is never called
    // outside the probe.
    if (p15card) {
        sc_pkcs15_unbind(p15card);
        p15card = nullptr;
    }
    if (card) {
        sc_disconnect_card(card);
        card = nullptr;
    }
    bound = false;
    hasPKI = false;
    // Enforce "no card => no channel" unconditionally: a borrowed channel
    // pointer must never outlive the card state a raw-branch transmit would
    // otherwise dispatch through. runWithChannelPtr already clears these
    // before calling here, but keeping the invariant inside the recovery
    // primitive protects any future caller.
    if (bridge) {
        bridge->data.channel = nullptr;
        bridge->data.token = LibreSCRS::CancelToken{};
    }
}

void OpenSCSession::release() noexcept
{
    resetCardState();
    if (ctx) {
        sc_release_context(ctx);
        ctx = nullptr;
    }
    // The bridge reader is NOT in ctx->readers, so sc_release_context did
    // not free it; resetting frees the sc_reader + private-data block.
    // Must run after sc_disconnect_card/sc_release_context, which used
    // card->reader = &bridge->reader.
    bridge.reset();
}

// Unrecognised drivers stay Unknown (nullptr quirks: nothing beyond
// evidence-derived kind/state is advertised for them).
LibreSCRS::Plugin::Internal::FamilyId familyFromDriverShortName(const char* shortName) noexcept
{
    using LibreSCRS::Plugin::Internal::FamilyId;
    if (!shortName)
        return FamilyId::Unknown;
    const std::string_view name{shortName};
    if (name == "PIV-II")
        return FamilyId::Piv;
    if (name == "srbeid") // vendored driver for the Serbian CardEdge applet
        return FamilyId::CurrentLkCardEdge;
    if (name == "srbeid2") // second-generation Serbian eID applet suite
        return FamilyId::AppletSuiteGen2;
    return FamilyId::Unknown;
}

sc_pkcs15_object_t* selectKeyByReferenceAndType(sc_pkcs15_object_t* const* keyObjs, int keyCount,
                                                std::uint16_t keyReference, unsigned int keyType) noexcept
{
    for (int i = 0; i < keyCount; ++i) {
        if (!keyObjs[i] || keyObjs[i]->type != keyType)
            continue;
        const auto* keyInfo = static_cast<const sc_pkcs15_prkey_info_t*>(keyObjs[i]->data);
        if (keyInfo && static_cast<std::uint16_t>(keyInfo->key_reference) == keyReference)
            return keyObjs[i];
    }
    return nullptr;
}

std::uint16_t keySizeBitsFromKeyInfo(const sc_pkcs15_prkey_info_t& keyInfo) noexcept
{
    return static_cast<std::uint16_t>(keyInfo.modulus_length != 0 ? keyInfo.modulus_length : keyInfo.field_length);
}

std::size_t ecdsaSignatureLength(std::size_t fieldLengthBits) noexcept
{
    return 2 * ((fieldLengthBits + 7) / 8);
}

