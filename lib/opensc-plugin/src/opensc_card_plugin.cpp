class OpenSCCardPlugin final : public LibreSCRS::Plugin::CardPlugin
{
public:
    OpenSCCardPlugin()
    {
        setIdentity(std::string{LibreSCRS::Plugin::generated::opensc::kPluginId},
                    std::string{LibreSCRS::Plugin::generated::opensc::kDisplayName},
                    /*priority=*/800);
    }

    ~OpenSCCardPlugin() override
    {
        std::lock_guard lock(mtx);
        // OpenSCSession dtor releases libopensc resources; clearing the
        // map invokes it for every entry.
        sessions.clear();
    }

    LibreSCRS::Plugin::CardCapabilities capabilities() const override
    {
        return LibreSCRS::Plugin::generated::opensc::kCapabilities;
    }

    std::span<const LibreSCRS::Plugin::Atr> supportedAtrs() const noexcept override
    {
        return LibreSCRS::Plugin::generated::opensc::kAtrs;
    }

    bool canHandleConnection(std::span<const std::uint8_t> atr,
                             LibreSCRS::SmartCard::CardSession& cardSession) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);

        // Start a fresh session for this connection, tearing down any prior
        // state keyed to the same PCSCConnection* (re-entrancy safety on
        // card re-insert against the same reader). The erased value's
        // ~OpenSCSession() releases libopensc resources.
        sessions.erase(&conn);

        OpenSCSession session;
        session.readerName = conn.readerName();

        int rc = sc_establish_context(&session.ctx, "librescrs");
        if (rc < 0)
            return false;

        // Bind libopensc to the agent's single LM PCSCConnection via the
        // bridge reader, instead of opening a second sc_connect_card. The
        // built-in pcsc reader_driver stays as ctx->reader_driver (its init
        // already ran in sc_establish_context, harmlessly); we drive our own
        // injected reader, whose transmit op routes through conn.transmit().
        // Use the ATR the agent already read for this session (the
        // canHandleConnection `atr` argument == CardSession::atr()); no extra
        // SCardStatus, and it cannot throw across the plugin boundary the way
        // a detached-connection getATR() would.
        session.bridge = std::make_unique<LibreSCRS::OpenSc::Bridge::OpenScBridge>();
        session.bridge->data.conn = &conn;
        session.bridge->readerName = conn.readerName();
        LibreSCRS::OpenSc::Bridge::initBridgeReader(session.ctx, *session.bridge, atr);

        rc = sc_connect_card(&session.bridge->reader, &session.card);
        if (rc < 0) {
            // ~OpenSCSession runs on scope exit and releases ctx + bridge.
            return false;
        }

        rc = sc_pkcs15_bind(session.card, nullptr, &session.p15card);
        if (rc < 0) {
            return false;
        }

        // Detect PKI presence (PIN + RSA objects). No longer exposed
        // externally — kept for diagnostic/read-path hinting.
        sc_pkcs15_object_t* pinObjs[8];
        int pinCount = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_AUTH_PIN, pinObjs, 8);

        sc_pkcs15_object_t* keyObjs[8];
        int keyCount = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_PRKEY_RSA, keyObjs, 8);

        session.hasPKI = (pinCount > 0 || keyCount > 0);

        sessions.emplace(&conn, std::move(session));
        return true;
    }

    LibreSCRS::Plugin::ReadResult doReadCard(LibreSCRS::SmartCard::CardSession& cardSession,
                                             GroupCallback onGroup) const override
    {
        using LibreSCRS::Plugin::ReadResult;
        try {
            LibreSCRS::Plugin::CardData data;
            data.cardType = "opensc";

            auto emitGroup = [&](LibreSCRS::Plugin::CardFieldGroup&& group) {
                if (onGroup)
                    onGroup(data.cardType, group);
                data.groups.push_back(std::move(group));
            };

            auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
            std::lock_guard lock(mtx);
            auto it = sessions.find(&conn);
            if (it == sessions.end() || !it->second.p15card) {
                return ReadResult::unsupportedCard(
                    LibreSCRS::Auth::ErrorKeys::unsupportedCard(),
                    std::string{"opensc session not bound — canHandleConnection was not called or failed"});
            }
            auto& session = it->second;

            // Token info group. Field keys ("label" / "serial_number" /
            // "manufacturer") MUST match the well-known token-header keys
            // GUI hosts use to localise the row labels; the same keys are
            // emitted by readTokenInfo() below, keeping the two surfaces
            // consistent.
            LibreSCRS::Plugin::CardFieldGroup tokenGroup;
            tokenGroup.groupKey = "token";
            tokenGroup.groupLabel = "Token Info";

            auto* ti = session.p15card->tokeninfo;
            if (ti) {
                auto addField = [&](const std::string& key, const std::string& label, const char* val) {
                    if (val && val[0] != '\0') {
                        std::string s(val);
                        tokenGroup.fields.push_back(
                            {key, label, LibreSCRS::Plugin::FieldType::Text, {s.begin(), s.end()}});
                    }
                };
                addField("label", "Label", ti->label);
                addField("serial_number", "Serial Number", ti->serial_number);
                addField("manufacturer", "Manufacturer", ti->manufacturer_id);

                // Decode flags to human-readable string
                std::string flagStr;
                if (ti->flags & SC_PKCS15_TOKEN_PRN_GENERATION)
                    flagStr += "PRN ";
                if (ti->flags & SC_PKCS15_TOKEN_LOGIN_REQUIRED)
                    flagStr += "Login required ";
                if (!flagStr.empty()) {
                    flagStr.pop_back(); // remove trailing space
                    tokenGroup.fields.push_back(
                        {"flags", "Flags", LibreSCRS::Plugin::FieldType::Text, {flagStr.begin(), flagStr.end()}});
                }
            }
            emitGroup(std::move(tokenGroup));

            // Certificates summary group
            sc_pkcs15_object_t* certObjs[16];
            int certCount = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_CERT_X509, certObjs, 16);

            if (certCount > 0) {
                LibreSCRS::Plugin::CardFieldGroup certGroup;
                certGroup.groupKey = "certificates";
                certGroup.groupLabel = "Certificates";

                for (int i = 0; i < certCount; ++i) {
                    auto* certInfo = static_cast<sc_pkcs15_cert_info_t*>(certObjs[i]->data);
                    sc_pkcs15_cert_t* certRaw = nullptr;
                    int rc = sc_pkcs15_read_certificate(session.p15card, certInfo, 0, &certRaw);

                    // Pkcs15CertPtr wraps the cert across extractSubjectCN
                    // (allocates the CN std::string) and the throwing
                    // certGroup.fields.push_back below.
                    Pkcs15CertPtr cert(certRaw);
                    std::string cn = "(unreadable)";
                    if (rc == 0 && cert) {
                        cn = extractSubjectCN(cert->data.value, cert->data.len);
                    }

                    std::string key = "cert_" + std::to_string(i);
                    std::string label =
                        certObjs[i]->label[0] ? certObjs[i]->label : ("Certificate " + std::to_string(i));
                    certGroup.fields.push_back(
                        {key, label, LibreSCRS::Plugin::FieldType::Text, {cn.begin(), cn.end()}});
                }
                emitGroup(std::move(certGroup));
            }

            // PIN state is surfaced via the typed getPINList() override
            // (PinStatusEntry vector), not via the readCard() data groups.

            return ReadResult::ok(std::move(data));
        } catch (const std::exception& ex) {
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{"opensc readCard failed: "} + ex.what());
        } catch (...) {
            return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                                  std::string{"opensc readCard failed (unknown error)"});
        }
    }

    LibreSCRS::Plugin::CardFieldGroup readTokenInfo(LibreSCRS::SmartCard::CardSession& cardSession) const override
    {
        // Best-effort token-info read mirroring the pkcs15-plugin contract.
        // The group key/label are populated up-front so the presentation
        // layer can render its placeholder header from an empty group when
        // nothing could be read (no bound p15card, no tokeninfo).
        //
        // Field keys ("label", "serial_number", "manufacturer") are the
        // well-known token-header keys consumed by GUI hosts; cross-plugin
        // key drift would silently demote to placeholder rendering even
        // when the data is present.
        LibreSCRS::Plugin::CardFieldGroup group;
        group.groupKey = "token";
        group.groupLabel = "Token Info";

        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);
        auto it = sessions.find(&conn);
        if (it == sessions.end() || !it->second.p15card)
            return group;

        auto* ti = it->second.p15card->tokeninfo;
        if (!ti)
            return group;

        // CardFieldGroup::addText throws on (empty value, empty fields) by
        // design — skip empty values up-front so a single missing field can
        // never cascade into a fully empty group.
        auto safeAddText = [&](std::string_view key, std::string_view label, const char* value) {
            if (!value || value[0] == '\0')
                return;
            std::string_view sv(value);
            try {
                group.addText(key, label, sv);
            } catch (const std::exception& ex) {
                std::clog << "[librescrs.opensc.plugin] readTokenInfo: addText(" << key << ") threw: " << ex.what()
                          << "\n";
            } catch (...) {
                std::clog << "[librescrs.opensc.plugin] readTokenInfo: addText threw (non-std exception)\n";
            }
        };

        safeAddText("label", "Label", ti->label);
        safeAddText("serial_number", "Serial Number", ti->serial_number);
        safeAddText("manufacturer", "Manufacturer", ti->manufacturer_id);
        return group;
    }

    std::vector<LibreSCRS::Plugin::CertificateData>
    readCertificates(LibreSCRS::SmartCard::CardSession& cardSession) const override
    {
        std::vector<LibreSCRS::Plugin::CertificateData> result;

        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);
        auto it = sessions.find(&conn);
        if (it == sessions.end() || !it->second.p15card)
            return result;
        auto& session = it->second;

        sc_pkcs15_object_t* certObjs[16];
        int certCount = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_CERT_X509, certObjs, 16);

        for (int i = 0; i < certCount; ++i) {
            auto* certInfo = static_cast<sc_pkcs15_cert_info_t*>(certObjs[i]->data);
            sc_pkcs15_cert_t* certRaw = nullptr;
            int rc = sc_pkcs15_read_certificate(session.p15card, certInfo, 0, &certRaw);
            if (rc < 0 || !certRaw)
                continue;

            // Pkcs15CertPtr keeps the cert alive across cd.derBytes.assign()
            // (throws bad_alloc on large certs) and the throwable
            // result.push_back below — both leaked the cert previously.
            Pkcs15CertPtr cert(certRaw);

            LibreSCRS::Plugin::CertificateData cd;
            cd.label = certObjs[i]->label;
            cd.derBytes.assign(cert->data.value, cert->data.value + cert->data.len);
            // The PKCS#15 object id IS the PKCS#11 CKA_ID — surface it so the
            // in-process sign path selects THIS exact key by CKA_ID rather than
            // the non-unique label.
            cd.ckaId.assign(certInfo->id.value, certInfo->id.value + certInfo->id.len);

            // Try to find associated private key for FID and key size
            sc_pkcs15_object_t* keyObj = nullptr;
            rc = sc_pkcs15_find_prkey_by_id(session.p15card, &certInfo->id, &keyObj);
            if (rc == 0 && keyObj) {
                auto* keyInfo = static_cast<sc_pkcs15_prkey_info_t*>(keyObj->data);
                cd.keyFID = static_cast<std::uint16_t>(keyInfo->key_reference);
                cd.keySizeBits = static_cast<std::uint16_t>(keyInfo->modulus_length);
            }

            result.push_back(std::move(cd));
        }

        return result;
    }

    LibreSCRS::Plugin::PINResult verifyPIN(LibreSCRS::SmartCard::CardSession& cardSession,
                                           const LibreSCRS::Secure::String& pin) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);
        auto it = sessions.find(&conn);
        if (it == sessions.end() || !it->second.p15card)
            return {};
        auto& session = it->second;

        sc_pkcs15_object_t* pinObjs[4];
        int count = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_AUTH_PIN, pinObjs, 4);
        if (count <= 0)
            return {};

        auto pinView = pin.view();
        int rc = sc_pkcs15_verify_pin(session.p15card, pinObjs[0], reinterpret_cast<const uint8_t*>(pinView.data()),
                                      pinView.size());

        // Refresh tries_left from card (verify may not update auth_info on all drivers)
        sc_pkcs15_get_pin_info(session.p15card, pinObjs[0]);
        auto* authInfo = static_cast<sc_pkcs15_auth_info_t*>(pinObjs[0]->data);

        LibreSCRS::Plugin::PINResult result;
        if (authInfo->tries_left >= 0)
            result.retriesLeft = authInfo->tries_left;
        result.blocked = (authInfo->tries_left == 0);
        result.outcome = LibreSCRS::Plugin::classifyPinOutcome(result, rc == 0);
        return result;
    }

    std::vector<LibreSCRS::Plugin::PinStatusEntry>
    getPINList(LibreSCRS::SmartCard::CardSession& cardSession) const override
    {
        std::vector<LibreSCRS::Plugin::PinStatusEntry> result;

        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);
        auto it = sessions.find(&conn);
        if (it == sessions.end() || !it->second.p15card)
            return result;
        auto& session = it->second;

        sc_pkcs15_object_t* pinObjs[8];
        int pinCount = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_AUTH_PIN, pinObjs, 8);
        if (pinCount <= 0)
            return result;

        // Lifecycle classification runs on the already-parsed AODF data
        // only — no APDUs, preserving the non-consumption invariant.
        const char* driverShortName =
            (session.card && session.card->driver) ? session.card->driver->short_name : nullptr;
        return LibreSCRS::OpenSc::buildPinStatusEntries(pinObjs, pinCount, driverShortName);
    }

    LibreSCRS::Plugin::PINResult changePIN(LibreSCRS::SmartCard::CardSession& cardSession, std::string_view pinLabel,
                                           const LibreSCRS::Secure::String& oldPin,
                                           const LibreSCRS::Secure::String& newPin) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);
        auto it = sessions.find(&conn);
        if (it == sessions.end() || !it->second.p15card) {
            LibreSCRS::Plugin::PINResult r;
            r.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return r;
        }
        auto& session = it->second;

        sc_pkcs15_object_t* pinObjs[4];
        int count = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_AUTH_PIN, pinObjs, 4);
        if (count <= 0) {
            LibreSCRS::Plugin::PINResult r;
            r.outcome = LibreSCRS::Plugin::PINResultOutcome::PluginError;
            return r;
        }

        return LibreSCRS::OpenSc::changePinWithSelector(session.p15card, pinObjs, count, pinLabel, oldPin, newPin,
                                                        &sc_pkcs15_change_pin, &sc_pkcs15_get_pin_info);
    }

    LibreSCRS::Plugin::CredentialCounters readCounters(LibreSCRS::SmartCard::CardSession& cardSession,
                                                       std::string_view /*pinLabel*/) const override
    {
        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);
        auto it = sessions.find(&conn);
        if (it == sessions.end() || !it->second.p15card)
            return {};
        auto& session = it->second;

        sc_pkcs15_object_t* pinObjs[4];
        int count = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_AUTH_PIN, pinObjs, 4);
        if (count <= 0)
            return {};

        int rc = sc_pkcs15_get_pin_info(session.p15card, pinObjs[0]);
        if (rc < 0)
            return {};
        auto* authInfo = static_cast<sc_pkcs15_auth_info_t*>(pinObjs[0]->data);
        LibreSCRS::Plugin::CredentialCounters c;
        if (authInfo->tries_left >= 0)
            c.retriesLeft = authInfo->tries_left;
        if (authInfo->max_tries > 0)
            c.retriesMax = authInfo->max_tries;
        // OpenSC's sc_pkcs15_auth_info models no usage/reset counter, so
        // uses*/unblocksLeft stay absent — the documented OpenSC limit.
        return c;
    }

    LibreSCRS::Plugin::SignResult doSign(LibreSCRS::SmartCard::CardSession& cardSession, std::uint16_t keyReference,
                                         std::span<const std::uint8_t> data,
                                         LibreSCRS::Plugin::SignMechanism mechanism) const override
    {
        auto pluginError = []() {
            LibreSCRS::Plugin::SignResult r;
            r.outcome = LibreSCRS::Plugin::SignResultOutcome::PluginError;
            return r;
        };

        // 4.0 ABI v6 reserves the ECDSA_SHA{256,384,512} mechanisms. This plugin
        // only supports RSA_PKCS — surface anything else as NotImplemented
        // so callers can route to an ECDSA-capable plugin (or a future
        // extension of this driver) instead of producing a silently RSA-
        // signed blob for an ECDSA request.
        if (mechanism != LibreSCRS::Plugin::SignMechanism::RSA_PKCS) {
            LibreSCRS::Plugin::SignResult r;
            r.outcome = LibreSCRS::Plugin::SignResultOutcome::NotImplemented;
            return r;
        }

        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);
        auto it = sessions.find(&conn);
        if (it == sessions.end() || !it->second.p15card)
            return pluginError();
        auto& session = it->second;

        // Find private key by reference
        sc_pkcs15_object_t* keyObjs[8];
        int keyCount = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_PRKEY_RSA, keyObjs, 8);

        sc_pkcs15_object_t* targetKey = nullptr;
        for (int i = 0; i < keyCount; ++i) {
            auto* keyInfo = static_cast<sc_pkcs15_prkey_info_t*>(keyObjs[i]->data);
            if (static_cast<uint16_t>(keyInfo->key_reference) == keyReference) {
                targetKey = keyObjs[i];
                break;
            }
        }
        if (!targetKey)
            return pluginError();

        auto* keyInfo = static_cast<sc_pkcs15_prkey_info_t*>(targetKey->data);
        size_t sigLen = keyInfo->modulus_length / 8; // RSA signature length in bytes
        std::vector<uint8_t> sig(sigLen);

        int rc = sc_pkcs15_compute_signature(session.p15card, targetKey,
                                             SC_ALGORITHM_RSA_PAD_PKCS1_TYPE_01 | SC_ALGORITHM_RSA_HASH_NONE,
                                             data.data(), data.size(), sig.data(), sig.size(), nullptr);

        if (rc < 0)
            return pluginError();
        sig.resize(static_cast<size_t>(rc));
        LibreSCRS::Plugin::SignResult result;
        result.signature = std::move(sig);
        result.outcome = LibreSCRS::Plugin::SignResultOutcome::Ok;
        return result;
    }

    LibreSCRS::Plugin::DecipherResult doDecipher(LibreSCRS::SmartCard::CardSession& cardSession,
                                                 std::uint16_t keyReference, std::span<const std::uint8_t> ciphertext,
                                                 LibreSCRS::Plugin::DecipherMechanism mechanism) const override
    {
        auto pluginError = []() {
            LibreSCRS::Plugin::DecipherResult r;
            r.outcome = LibreSCRS::Plugin::DecipherResultOutcome::PluginError;
            return r;
        };

        // This release supports only PKCS#1 v1.5 decrypt (SR cards are v1.5
        // only, no OAEP). Surface any other mechanism as NotImplemented so a
        // caller can route to a future OAEP-capable driver instead of silently
        // producing a v1.5-stripped result.
        if (mechanism != LibreSCRS::Plugin::DecipherMechanism::RSA_PKCS1_V15) {
            LibreSCRS::Plugin::DecipherResult r;
            r.outcome = LibreSCRS::Plugin::DecipherResultOutcome::NotImplemented;
            return r;
        }

        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);
        auto it = sessions.find(&conn);
        if (it == sessions.end() || !it->second.p15card)
            return pluginError();
        auto& session = it->second;

        // Find private key by reference (same resolution as doSign).
        sc_pkcs15_object_t* keyObjs[8];
        int keyCount = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_PRKEY_RSA, keyObjs, 8);

        sc_pkcs15_object_t* targetKey = nullptr;
        for (int i = 0; i < keyCount; ++i) {
            auto* keyInfo = static_cast<sc_pkcs15_prkey_info_t*>(keyObjs[i]->data);
            if (static_cast<uint16_t>(keyInfo->key_reference) == keyReference) {
                targetKey = keyObjs[i];
                break;
            }
        }
        if (!targetKey)
            return pluginError();

        auto* keyInfo = static_cast<sc_pkcs15_prkey_info_t*>(targetKey->data);
        size_t outCap = keyInfo->modulus_length / 8; // RSA block size in bytes
        std::vector<uint8_t> out(outCap);

        // Raw RSA decrypt + software PKCS#1 v1.5 unpad. The srbeid driver
        // advertises only SC_ALGORITHM_RSA_RAW and wires decipher to the raw
        // c^d mod N transform (card-srbeid.c:91,287), so it returns the full
        // padded block. Requesting SC_ALGORITHM_RSA_PAD_PKCS1_TYPE_02 makes
        // libopensc take the "card does raw, host strips padding" path
        // (sc_get_encoding_flags: pflags=TYPE_02, sflags=PAD_NONE —
        // padding.c:728) and then strip the v1.5 type-02 padding in
        // sc_pkcs15_decipher (pkcs15-sec.c:316). TYPE_02 (not TYPE_01) is the
        // decryption padding marker; TYPE_01 is the signing form. Verified
        // against the vendored OpenSC #3701 source.
        int rc = sc_pkcs15_decipher(session.p15card, targetKey, SC_ALGORITHM_RSA_PAD_PKCS1_TYPE_02, ciphertext.data(),
                                    ciphertext.size(), out.data(), out.size(), nullptr);
        if (rc < 0)
            return pluginError();
        out.resize(static_cast<size_t>(rc));
        LibreSCRS::Plugin::DecipherResult result;
        result.plaintext = std::move(out);
        result.outcome = LibreSCRS::Plugin::DecipherResultOutcome::Ok;
        return result;
    }

    std::vector<LibreSCRS::Plugin::KeyReference>
    discoverKeyReferences(LibreSCRS::SmartCard::CardSession& cardSession) const override
    {
        std::vector<LibreSCRS::Plugin::KeyReference> result;

        auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
        std::lock_guard lock(mtx);
        auto it = sessions.find(&conn);
        if (it == sessions.end() || !it->second.p15card)
            return result;
        auto& session = it->second;

        sc_pkcs15_object_t* keyObjs[8];
        int keyCount = sc_pkcs15_get_objects(session.p15card, SC_PKCS15_TYPE_PRKEY_RSA, keyObjs, 8);

        for (int i = 0; i < keyCount; ++i) {
            auto* keyInfo = static_cast<sc_pkcs15_prkey_info_t*>(keyObjs[i]->data);
            result.push_back({keyObjs[i]->label, static_cast<std::uint16_t>(keyInfo->key_reference)});
        }

        return result;
    }

    void clearCredentials(LibreSCRS::SmartCard::CardSession& cardSession) noexcept override
    {
        try {
            auto& conn = LibreSCRS::SmartCard::detail::unwrap(cardSession);
            std::lock_guard lock(mtx);
            // Erasing the entry invokes ~OpenSCSession on the held value.
            sessions.erase(&conn);
        } catch (...) {
            // clearCredentials is noexcept — swallow unwrap/lock failures.
        }
    }

private:
    mutable std::mutex mtx;
    mutable std::map<const LibreSCRS::SmartCard::Internal::PCSCConnection*, OpenSCSession> sessions;
};

