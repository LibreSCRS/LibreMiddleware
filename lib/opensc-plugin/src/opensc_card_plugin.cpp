bool driverPresent(const sc_context_t* ctx, std::string_view shortName) noexcept
{
    if (!ctx)
        return false;
    for (const auto* driver : ctx->card_drivers) {
        if (!driver)
            break; // the array is NULL-terminated
        if (driver->short_name && shortName == driver->short_name)
            return true;
    }
    return false;
}

bool efDirAdvertisesAppletSuiteGen2(const std::function<LibreSCRS::SmartCard::Internal::APDUResponse(
                                        const LibreSCRS::SmartCard::Internal::APDUCommand&)>& transmit)
{
    using LibreSCRS::SmartCard::Internal::readBinary;
    using LibreSCRS::SmartCard::Internal::selectByFileId;

    // Every probe SELECT: P2=0C, no Le — SELECT-with-FCI carrying DO97 Le!=00
    // is the measured killer of a live SM channel (SW 6988 → channel Failed),
    // and this walk must never kill ANOTHER provider's tunnel.
    auto mf = transmit(selectByFileId(0x3F, 0x00, /*p2=*/0x0C));
    if (!mf.isSuccess())
        return false;
    auto dir = transmit(selectByFileId(0x2F, 0x00, /*p2=*/0x0C));
    if (!dir.isSuccess())
        return false;

    // READ BINARY, searching for the AppletSuiteGen2 discriminator — the
    // registered application-template AID prefix — after each chunk and
    // returning as soon as it is found. Through the LM transport (both the
    // raw connection here and the SM tunnel) a single READ returns the whole
    // EF.DIR in one pass, terminated by 6282 (ISO 7816-4: end of file reached
    // before Le bytes). The per-96-byte chunking a plain SCardTransmit shows
    // is a reader-tool artefact that does not occur on this path.
    //
    // CRITICAL — never issue a READ at or past end of file. Continue ONLY on
    // a FULL 256-byte 9000 chunk, where more data genuinely may follow; a
    // 6282, a short read, or any other status word ends the walk. Probing one
    // offset past the last data-bearing read is exactly what some cards answer
    // with an SM-fatal 6988, which — when this probe runs over ANOTHER
    // provider's live SM channel (the live-SM claim path) — would tear that
    // tunnel down. The concatenation across full chunks still lets an AID
    // template split across a 256-byte boundary survive a genuinely multi-read
    // file.
    static constexpr std::uint8_t kAidPrefix[] = {0xF3, 0x81, 0x00, 0x00, 0x02};
    std::vector<std::uint8_t> content;
    for (std::uint16_t offset = 0; offset < 0x8000;) {
        auto chunk = transmit(readBinary(offset, /*length=*/0)); // Le=00 → up to 256 bytes
        const std::uint16_t sw = chunk.statusWord();
        if ((sw == 0x9000 || sw == 0x6282) && !chunk.data.empty())
            content.insert(content.end(), chunk.data.begin(), chunk.data.end());
        if (std::search(content.begin(), content.end(), std::begin(kAidPrefix), std::end(kAidPrefix)) != content.end())
            return true;
        if (sw != 0x9000 || chunk.data.size() < 256)
            break; // EOF (6282 / short read) or any error — do NOT read further
        offset = static_cast<std::uint16_t>(offset + chunk.data.size());
    }
    return false;
}

ChannelRunReport runWithChannelPtr(OpenSCSession& s, LibreSCRS::SecureChannel::ISecureChannel* channel,
                                   LibreSCRS::CancelToken token, const std::function<void(OpenSCSession&)>& fn,
                                   const std::function<void()>& releaseChannel)
{
    using LibreSCRS::SecureChannel::ChannelState;

    ChannelRunReport report;
    s.bridge->data.channel = channel; // nullptr = raw branch (CardEdge and friends)
    if (channel != nullptr)
        s.bridge->data.token = token;

    // Deferred bind runs UNDER the active holder so every bind APDU rides
    // the tunnel. The holder spans the whole libopensc call; inside it, only
    // lock-free accessors may touch the session (the holder owns the session
    // mutex for its lifetime).
    int r = SC_SUCCESS;
    bool fnThrew = false;
    if (!s.bound) {
        r = sc_connect_card(&s.bridge->reader, &s.card);
        if (r == SC_SUCCESS)
            r = sc_pkcs15_bind(s.card, nullptr, &s.p15card);
        s.bound = (r == SC_SUCCESS);
    }
    if (r == SC_SUCCESS) {
        report.ran = true;
        // The operation body (fn) allocates card-sized buffers whose length
        // comes from card-reported key sizes, so a std::bad_alloc is reachable
        // — and NO C++ exception may cross the plugin ABI boundary
        // (CardPlugin.h: dlopen'd with a potentially-mismatched C++ runtime =
        // undefined behaviour). Contain it here and fold it into the report as
        // a transport-class failure; the cleanup below still runs, and the
        // caller maps an un-completed operation to a communication/plugin
        // error.
        try {
            fn(s);
        } catch (...) {
            fnThrew = true;
        }
    }

    // Verdict BY CHANNEL STATE, never by SW pattern: a cancel leaves the
    // channel Open (no SM/SSC movement) and is reported via the token; a
    // dead tunnel reads Failed/Closed here regardless of which SW the card
    // returned last.
    report.cancelled = token.isCancelled();
    report.channelFatal = (channel != nullptr) && channel->state() != ChannelState::Open;
    report.bindFailed = (r != SC_SUCCESS) || fnThrew;

    s.bridge->data.channel = nullptr;
    s.bridge->data.token = LibreSCRS::CancelToken{};
    releaseChannel(); // production: the holder's RAII release (transaction + session mutex)

    // Partial teardown on a dead tunnel AND on a failed bind (a cancel
    // during bind otherwise leaks a second sc_card on the same bridge). A
    // cancel during fn() with a healthy channel resets nothing.
    if (report.channelFatal || report.bindFailed)
        s.resetCardState();
    return report;
}

ChannelRunReport runUnderChannel(LibreSCRS::SmartCard::CardSession& cardSession, OpenSCSession& s,
                                 LibreSCRS::CancelToken token, const std::function<void(OpenSCSession&)>& fn)
{
    using LibreSCRS::SmartCard::Internal::HolderChannelAccessor;

    // A credential-provider callback must NOT synchronously invoke another
    // plugin operation on the same session: the per-session mutex is
    // non-recursive. The debug assert makes that ban enforceable — no
    // in-tree operation dispatches another operation on the same session, so
    // the only way to reach a non-owning try_lock is the forbidden
    // same-thread re-entry (a provider callback) or a caller violating
    // CardSession's single-session thread-safety contract. In a release
    // build the debug assert is gone; the blocking lock() that follows is a
    // correct serialisation ONLY for the genuine cross-thread case — for the
    // forbidden same-thread re-entry, locking a std::mutex the thread already
    // holds is itself undefined behaviour. There is no legitimate re-enterer,
    // so this is a defensive tail, not a supported path.
    std::unique_lock opLock(s.opMutex, std::try_to_lock);
    assert(opLock.owns_lock() && "plugin operation re-entered on the same session (credential provider re-entry?)");
    if (!opLock.owns_lock())
        opLock.lock();

    std::optional<LibreSCRS::SmartCard::ActiveChannelHolder> holder;
    LibreSCRS::SecureChannel::ISecureChannel* channel = nullptr;
    if (s.requiresPace) {
        // Ride the protocol that already holds a live SM tunnel on this
        // session (e.g. PACE from the emrtd display flow) rather than
        // assuming PACE-CAN (pkcs15-plugin precedent). The CAN itself flows
        // through CardSession's credential provider / cache on demand.
        LibreSCRS::SmartCard::SmProtocolRequest req{
            LibreSCRS::SmartCard::PaceRequest{LibreSCRS::Auth::PaceSecretKind::Can}};
        if (auto live = cardSession.activatedProtocol())
            req = *live;
        auto holderResult = cardSession.activateChannelWithSm(pkcs15AppletAid(), req, token);
        if (!holderResult) {
            // Activation failure never tears card state down: a still-bound
            // session stays bound (nothing leaked), and the next operation
            // simply re-activates over the same ctx/bridge.
            ChannelRunReport report;
            report.activationFailed = true;
            report.activationError = holderResult.error();
            report.cancelled = token.isCancelled();
            return report;
        }
        holder.emplace(std::move(*holderResult));
        channel = HolderChannelAccessor::channel(*holder);
    }
    return runWithChannelPtr(s, channel, token, fn, [&holder]() { holder.reset(); });
}

// -- Activation-error vocabulary (declared in opensc_session.h) -------------

LibreSCRS::Plugin::ReadResult mapActivationErrorToReadResult(LibreSCRS::SecureChannel::ChannelActivationError err,
                                                             const char* what)
{
    using Err = LibreSCRS::SecureChannel::ChannelActivationError;
    using LibreSCRS::Plugin::ReadResult;
    switch (err) {
    case Err::Cancelled:
    case Err::UserCancelled:
        return ReadResult::cancelled();
    case Err::CredentialsRequired:
        return ReadResult::authenticationFailed(LibreSCRS::Auth::ErrorKeys::authFailed(),
                                                std::string{what} + ": CAN required");
    case Err::PaceWrongSecret:
        return ReadResult::authenticationFailed(LibreSCRS::Auth::ErrorKeys::authFailed(),
                                                std::string{what} + ": wrong CAN");
    case Err::CardRemoved:
        return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                              std::string{what} + ": card removed");
    default:
        return ReadResult::communicationError(LibreSCRS::Auth::ErrorKeys::genericComm(),
                                              std::string{what} + ": channel activation failed");
    }
}

