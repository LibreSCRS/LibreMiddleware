// OpenSC fallback for unknown PKCS#15-shaped cards. Sits BELOW specific
// plugins (rs-eid, rs-health, emrtd, eu-vrc — priorities 100-ish) but
// ABOVE the generic LM PKCS#15 parser (pkcs15-plugin, priority 900):
// OpenSC's full driver chain (srbeid, cardos, ias-ecc, openpgp, …)
// handles card-specific quirks the generic parser does not. Never
// matches by ATR — relies on canHandleConnection driving sc_pkcs15_bind()
// against the live session. kAtrs (from manifest.json) is intentionally empty.

std::string extractSubjectCN(const uint8_t* der, size_t len)
{
    // X509Ptr keeps the parsed cert alive across the std::string ctor at
    // the bottom of this function, which can throw std::bad_alloc on a
    // pathological allocator. The previous raw-X509* path leaked the
    // cert on that unwind because the explicit X509_free was unreachable.
    const uint8_t* p = der;
    X509Ptr cert(d2i_X509(nullptr, &p, static_cast<long>(len)));
    if (!cert)
        return "(unreadable)";

    X509_NAME* subject = X509_get_subject_name(cert.get());
    char buf[256] = {};
    X509_NAME_get_text_by_NID(subject, NID_commonName, buf, sizeof(buf));

    std::string cn(buf);
    return cn.empty() ? "(no CN)" : cn;
}

// Per-session OpenSC binding state. Owned by the plugin's session map,
// keyed by PCSCConnection*. A fresh entry is created on canHandleConnection()
// and torn down by ~OpenSCSession() (invoked when erased from the map, when
// the map itself is destroyed, or — critically — during stack unwind if
// `sessions.emplace(...)` throws bad_alloc on a partially-built session).
//
// Move-only RAII: the libopensc resources (ctx / card / p15card) are
// owned by exactly one OpenSCSession at any time. Copy is disabled to
// prevent double-free; move nulls out the source so the moved-from
// instance's dtor is a no-op.
class OpenSCSession
{
public:
    OpenSCSession() = default;
    ~OpenSCSession() noexcept
    {
        release();
    }

    OpenSCSession(const OpenSCSession&) = delete;
    OpenSCSession& operator=(const OpenSCSession&) = delete;

    OpenSCSession(OpenSCSession&& other) noexcept
        : ctx(other.ctx), card(other.card), p15card(other.p15card), readerName(std::move(other.readerName)),
          hasPKI(other.hasPKI), bridge(std::move(other.bridge))
    {
        other.ctx = nullptr;
        other.card = nullptr;
        other.p15card = nullptr;
        other.hasPKI = false;
    }

    OpenSCSession& operator=(OpenSCSession&& other) noexcept
    {
        if (this != &other) {
            release();
            ctx = other.ctx;
            card = other.card;
            p15card = other.p15card;
            readerName = std::move(other.readerName);
            hasPKI = other.hasPKI;
            bridge = std::move(other.bridge);
            other.ctx = nullptr;
            other.card = nullptr;
            other.p15card = nullptr;
            other.hasPKI = false;
        }
        return *this;
    }

    // Public for direct field-style use at call sites (mirrors prior POD
    // shape). All four owning pointers are managed by release() and the
    // move ctor; the std::string + bool are trivially handled by the
    // generated move ops.
    sc_context_t* ctx = nullptr;
    sc_card_t* card = nullptr;
    sc_pkcs15_card_t* p15card = nullptr;
    std::string readerName;
    bool hasPKI = false;

    // Single-session bridge: owns the librescrs-bridge sc_reader + its private
    // data at a stable heap address (survives this OpenSCSession's move into
    // the sessions map after sc_connect_card set card->reader = &reader). Holds
    // no PC/SC connection of its own — it routes libopensc through the LM
    // PCSCConnection. Released last in release() (it is NOT in ctx->readers, so
    // sc_release_context does not free it).
    std::unique_ptr<LibreSCRS::OpenSc::Bridge::OpenScBridge> bridge;

private:
    // Order matters: PKCS#15 binding holds references into the underlying
    // sc_card; the card must be disconnected before releasing the context.
    void release() noexcept
    {
        if (p15card) {
            sc_pkcs15_unbind(p15card);
            p15card = nullptr;
        }
        if (card) {
            sc_disconnect_card(card);
            card = nullptr;
        }
        if (ctx) {
            sc_release_context(ctx);
            ctx = nullptr;
        }
        // The bridge reader is NOT in ctx->readers, so sc_release_context did
        // not free it; resetting frees the sc_reader + private-data block.
        // Must run after sc_disconnect_card/sc_release_context, which used
        // card->reader = &bridge->reader.
        bridge.reset();
        hasPKI = false;
    }
};

