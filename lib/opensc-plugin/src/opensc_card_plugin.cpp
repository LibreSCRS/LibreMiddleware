/// @brief Builds lifecycle-classified PIN entries from parsed PKCS#15 auth
///        objects via the shared derivation engine.
///
/// Non-member seam so unit tests can drive it with synthetic sc_pkcs15
/// objects (the test target compiles this translation unit directly).
/// Reads ONLY the already-parsed structures — no card I/O — so calling it
/// from getPINList preserves the non-consumption invariant.
std::vector<LibreSCRS::Plugin::PinStatusEntry> buildPinStatusEntries(sc_pkcs15_object_t* const* pinObjs, int pinCount,
                                                                     const char* driverShortName)
{
    namespace Internal = LibreSCRS::Plugin::Internal;

    std::vector<LibreSCRS::Plugin::PinStatusEntry> result;
    if (!pinObjs || pinCount <= 0)
        return result;

    // Pass 1: per-object evidence from the parsed AODF attributes. The
    // needs-change signal is a bit test: drivers OR
    // SC_PIN_STATE_NEEDS_CHANGE onto the logged state.
    std::vector<Internal::PinEvidence> evidence;
    std::vector<const sc_pkcs15_object_t*> objs; // aligned with evidence
    std::vector<const sc_pkcs15_auth_info_t*> infos;
    evidence.reserve(static_cast<std::size_t>(pinCount));
    objs.reserve(static_cast<std::size_t>(pinCount));
    infos.reserve(static_cast<std::size_t>(pinCount));
    for (int i = 0; i < pinCount; ++i) {
        const sc_pkcs15_object_t* obj = pinObjs[i];
        const auto* info = obj ? static_cast<const sc_pkcs15_auth_info_t*>(obj->data) : nullptr;
        if (!info)
            continue;

        Internal::PinEvidence ev;
        // An empty AODF label must never be advertised verbatim: the
        // changePIN selector contract reserves the EMPTY selector for the
        // legacy default-PIN fallback, so "" would alias this record onto
        // a DIFFERENT credential. The documented "pin_<reference>" form
        // is the non-aliasing substitute — resolveChangePinTarget accepts
        // it verbatim and addresses the record by its reference.
        const auto reference = static_cast<std::uint8_t>(info->attrs.pin.reference & 0xff);
        ev.label = obj->label[0] ? std::string{obj->label} : "pin_" + std::to_string(reference);
        ev.reference = reference;
        ev.ownId.assign(info->auth_id.value, info->auth_id.value + info->auth_id.len);
        const unsigned int flags = info->attrs.pin.flags;
        ev.localScope = (flags & SC_PKCS15_PIN_FLAG_LOCAL) != 0;
        // inQscdDf / paceEvidence stay false: the generic OpenSC path has
        // no signature-DF map and no PACE evidence.
        ev.soPinFlag = (flags & SC_PKCS15_PIN_FLAG_SO_PIN) != 0;
        ev.unblockingPinFlag = (flags & SC_PKCS15_PIN_FLAG_UNBLOCKING_PIN) != 0;
        ev.unblockDisabledFlag = (flags & SC_PKCS15_PIN_FLAG_UNBLOCK_DISABLED) != 0;
        ev.changeDisabledFlag = (flags & SC_PKCS15_PIN_FLAG_CHANGE_DISABLED) != 0;
        ev.initialized = (flags & SC_PKCS15_PIN_FLAG_INITIALIZED) != 0;
        // tries_left semantics: -1 = unknown; >= 0 = real count, 0 blocked.
        ev.blocked = (info->tries_left == 0);
        ev.needsChangeSignal = (info->logged_in & SC_PIN_STATE_NEEDS_CHANGE) != 0;
        evidence.push_back(std::move(ev));
        objs.push_back(obj);
        infos.push_back(info);
    }

    // Pass 2: resolve the AODF authId protection chain per the derivation
    // engine's contract — when object i is protected by auth object j,
    // record the protecting object's FULL id bytes on i (matched against
    // the target's ownId during derivation) and mark j as the unblocking
    // chain target.
    for (std::size_t i = 0; i < objs.size(); ++i) {
        const sc_pkcs15_id* protecting = &objs[i]->auth_id;
        if (protecting->len == 0)
            continue;
        for (std::size_t j = 0; j < objs.size(); ++j) {
            if (j == i)
                continue;
            if (sc_pkcs15_compare_id(&infos[j]->auth_id, protecting)) {
                evidence[i].authIdChainTarget =
                    std::vector<std::uint8_t>(protecting->value, protecting->value + protecting->len);
                evidence[j].unblockingPinFlag = true;
                break;
            }
        }
    }

    const Internal::FamilyQuirks* quirks = Internal::findFamilyQuirks(familyFromDriverShortName(driverShortName));

    for (std::size_t i = 0; i < evidence.size(); ++i) {
        auto entry = Internal::derivePinStatus(evidence[i], evidence, quirks);
        // Caller-populated counters/lengths (outside the engine's remit).
        const sc_pkcs15_auth_info_t* info = infos[i];
        if (info->tries_left >= 0)
            entry.retriesLeft = info->tries_left;
        if (info->attrs.pin.min_length > 0)
            entry.minLength = info->attrs.pin.min_length;
        if (info->attrs.pin.max_length > 0)
            entry.maxLength = info->attrs.pin.max_length;
        result.push_back(std::move(entry));
    }
    return result;
}

/// @brief Resolves the @c changePIN selector over the enumerated AUTH_PIN
///        objects.
///
/// Selector contract (see the @c changePIN doc in CardPlugin.h): an EMPTY
/// selector keeps the legacy default-PIN behaviour and resolves the FIRST
/// enumerated object; a non-empty selector must match an object's label
/// or the documented "pin_<reference>" form (decimal reference). A
/// non-empty selector that matches nothing resolves to @c nullptr — the
/// caller must refuse WITHOUT touching the card (mutating a PIN the host
/// did not address is never acceptable on multi-PIN cards).
sc_pkcs15_object_t* resolveChangePinTarget(sc_pkcs15_object_t* const* pinObjs, int pinCount, std::string_view pinLabel)
{
    if (!pinObjs || pinCount <= 0)
        return nullptr;
    if (pinLabel.empty())
        return pinObjs[0]; // legacy default-PIN path

    for (int i = 0; i < pinCount; ++i) {
        if (pinObjs[i] && std::string_view{pinObjs[i]->label} == pinLabel)
            return pinObjs[i];
    }

    constexpr std::string_view prefix = "pin_";
    if (pinLabel.starts_with(prefix)) {
        const std::string_view suffix = pinLabel.substr(prefix.size());
        int reference = 0;
        const auto [ptr, ec] = std::from_chars(suffix.data(), suffix.data() + suffix.size(), reference);
        if (ec == std::errc{} && ptr == suffix.data() + suffix.size() && reference >= 0) {
            for (int i = 0; i < pinCount; ++i) {
                const auto* info = pinObjs[i] ? static_cast<const sc_pkcs15_auth_info_t*>(pinObjs[i]->data) : nullptr;
                if (info && info->attrs.pin.reference == reference)
                    return pinObjs[i];
            }
        }
    }
    return nullptr;
}

