/// Maps libopensc's resolved card-driver identity to a quirk-table family.
/// Uses only the driver short_name that sc_connect_card already resolved —
/// no ATR probing or new detection here; unrecognised drivers stay Unknown
/// (nullptr quirks: nothing beyond evidence-derived kind/state is
/// advertised for them).
LibreSCRS::Plugin::Internal::FamilyId familyFromDriverShortName(const char* shortName) noexcept
{
    using LibreSCRS::Plugin::Internal::FamilyId;
    if (!shortName)
        return FamilyId::Unknown;
    const std::string_view name{shortName};
    if (name == "PIV-II")
        return FamilyId::Piv;
    if (name == "srbeid") // vendored driver for the Serbian CardEdge applet
        return FamilyId::CurrentLkCardEdge;
    return FamilyId::Unknown;
}

