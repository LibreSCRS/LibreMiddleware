#include <ef_dir.h>

#include <gtest/gtest.h>

using namespace LibreSCRS::SmartCard::Internal;

namespace {
// EF.DIR sa TRI zapisa, gde prva DVA nose ISTI AID a razlicite putanje.
// Tri, ne dva: sa dva kandidata i "uzmi prvi" i "uzmi poslednji" prolaze
// slucajno. Tacan je SREDNJI.
const std::vector<uint8_t> EF_DIR_DUPLICATE_AID = {
    0x61, 0x16, 0x4F, 0x0C, 0xA0, 0x00, 0x00, 0x00, 0x63, 0x50, 0x4B, 0x43, 0x53, 0x2D, 0x31, 0x35,
    0x50, 0x02, 0x4D, 0x46, 0x51, 0x02, 0x3F, 0x00, 0x61, 0x1C, 0x4F, 0x0C, 0xA0, 0x00, 0x00, 0x00,
    0x63, 0x50, 0x4B, 0x43, 0x53, 0x2D, 0x31, 0x35, 0x50, 0x06, 0x50, 0x4B, 0x43, 0x53, 0x31, 0x35,
    0x51, 0x04, 0x3F, 0x00, 0x50, 0x15, 0x61, 0x18, 0x4F, 0x07, 0xA0, 0x00, 0x00, 0x02, 0x47, 0x10,
    0x01, 0x50, 0x04, 0x49, 0x43, 0x41, 0x4F, 0x51, 0x07, 0xA0, 0x00, 0x00, 0x02, 0x47, 0x10, 0x01};
} // namespace

TEST(ParseEfDir, ReturnsEveryEntryNotJustPkcs15)
{
    auto entries = parseEfDir(EF_DIR_DUPLICATE_AID);
    ASSERT_EQ(entries.size(), 3u);
    EXPECT_EQ(entries[0].label, "MF");
    EXPECT_EQ(entries[1].label, "PKCS15");
    EXPECT_EQ(entries[2].label, "ICAO");
}

TEST(ParseEfDir, KeepsBothEntriesSharingAnAid)
{
    auto entries = parseEfDir(EF_DIR_DUPLICATE_AID);
    ASSERT_EQ(entries.size(), 3u);
    EXPECT_EQ(entries[0].aid, entries[1].aid);
    EXPECT_NE(entries[0].path, entries[1].path);
    EXPECT_EQ(entries[1].path, (std::vector<uint8_t>{0x3F, 0x00, 0x50, 0x15}));
}

TEST(ParseEfDir, EmptyInput)
{
    EXPECT_TRUE(parseEfDir({}).empty());
}
